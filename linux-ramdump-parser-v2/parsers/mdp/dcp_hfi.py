    def _hfi_prop_name(self, prop_id):
        """Return a human-readable name for an HFI property key ID (bits[19:0])."""
        name = (self.HFI_DISPLAY_PROP_NAMES.get(prop_id) or
                self.HFI_LAYER_PROP_NAMES.get(prop_id))
        return name if name else '0x{:08x}'.format(prop_id)

    def _hfi_cmd_name(self, cmd):
        """Return a human-readable name for an HFI command."""
        return self.HFI_CMD_NAMES.get(cmd, '0x{:08x}'.format(cmd))

    def _hfi_flags_str(self, flags):
        """Decode TX flag bitmask into a readable string."""
        parts = [name for bit, name in sorted(self.HFI_TX_FLAG_NAMES.items())
                 if flags & bit]
        return '|'.join(parts) if parts else 'NONE'

    def _hfi_queue_slot_count(self, elements, buffer_size, allocated_size):
        """Return a bounded queue-slot count and an optional diagnostic."""
        if not isinstance(elements, int):
            return 0, 'unreadable element count {}'.format(elements)
        if not isinstance(buffer_size, int):
            return 0, 'unreadable buffer size {}'.format(buffer_size)
        if not isinstance(allocated_size, int):
            return 0, 'unreadable allocation size {}'.format(allocated_size)
        if (buffer_size < self.MIN_QUEUE_BUFFER_SIZE or
                buffer_size % 4):
            return 0, 'invalid buffer size {}'.format(buffer_size)
        if buffer_size > self.MAX_QUEUE_BUFFER_SIZE:
            return 0, 'buffer size {} exceeds maximum {}'.format(
                buffer_size, self.MAX_QUEUE_BUFFER_SIZE)
        if allocated_size < buffer_size:
            return 0, 'allocation {} is smaller than one buffer'.format(
                allocated_size)

        allocated_slots = allocated_size // buffer_size
        requested_slots = elements if elements > 0 else allocated_slots
        scan_slots = self.MAX_QUEUE_SCAN_BYTES // buffer_size
        slot_count = min(requested_slots, allocated_slots,
                         self.MAX_QUEUE_SLOTS, scan_slots)
        notes = []
        if elements > self.MAX_QUEUE_SLOTS:
            notes.append('elements {} capped at {}'.format(
                elements, self.MAX_QUEUE_SLOTS))
        if allocated_slots > self.MAX_QUEUE_SLOTS:
            notes.append('allocation holds {} slots; capped at {}'.format(
                allocated_slots, self.MAX_QUEUE_SLOTS))
        if elements > 0 and elements > allocated_slots:
            notes.append('elements {} exceed allocation capacity {}'.format(
                elements, allocated_slots))
        if min(requested_slots, allocated_slots, self.MAX_QUEUE_SLOTS) > scan_slots:
            notes.append('scan budget limits traversal to {} slots'.format(
                scan_slots))
        if allocated_size % buffer_size:
            notes.append('ignoring {} trailing allocation bytes'.format(
                allocated_size % buffer_size))
        return slot_count, '; '.join(notes)

    def _hfi_decode_kv_payload(self, data, offset, payload_size):
        """
        Decode a KV-pair payload from a SET_PROPERTY packet.

        Wire layout (from hfi_packet.h + hfi_packer.c):
            u32  num_props
            for each prop:
                u32  key = prop_id[19:0] | version[23:20] | dsize_dwords[31:24]
                u32  value[dsize_dwords]

        Returns list of (prop_name, version, dsize, [value_u32, ...]).
        """
        import struct
        props = []
        if payload_size < 4:
            return props
        try:
            num_props = struct.unpack_from('<I', data, offset)[0]
            pos = offset + 4
            end = offset + payload_size
            for _ in range(num_props):
                if pos + 4 > end:
                    break
                key = struct.unpack_from('<I', data, pos)[0]
                pos += 4
                prop_id = key & 0x000FFFFF
                version = (key >> 20) & 0xF
                dsize = (key >> 24) & 0xFF
                if dsize == 0:
                    dsize = 1
                values = []
                for _ in range(dsize):
                    if pos + 4 > end:
                        break
                    values.append(struct.unpack_from('<I', data, pos)[0])
                    pos += 4
                props.append((self._hfi_prop_name(prop_id), version, dsize, values))
        except Exception as ex:
            print_out_str("hfi kv decode error: {}".format(ex))
        return props

    def _hfi_decode_frame_trigger_payload(self, data, offset, payload_size):
        """
        Decode FRAME_TRIGGER payload: single u32 commit flag.
        Returns decoded flag string (HFI_VALIDATE / HFI_COMMIT).
        """
        import struct
        if payload_size < 4:
            return 'N/A'
        try:
            flag = struct.unpack_from('<I', data, offset)[0]
            return self.HFI_COMMIT_FLAG_NAMES.get(flag, '0x{:x}'.format(flag))
        except Exception as ex:
            print_out_str("hfi frame trigger payload decode error: {}".format(ex))
            return 'N/A'

