    def _hfi_resolve_res_data_ptr(self, drv_data_ptr, client_id, log_fn):
        """
        Resolve drv_data->client_data[client_id].resource_info.res_data_mem.

        Tries DWARF field_offset() first; falls back to manually computed
        offsets from hfi_core.h when hfi_core.ko symbols are not loaded.

        Manual layout (64-bit ARM, hfi_core.h):
          struct client_data:
            drv_data*          PTR
            core_type enum     4 + pad 4
            session*           PTR
            client_state       4 + pad 4
            cb_fn*             PTR
            cb_data*           PTR
            ipc_info           4+4+PTR+4+4 = 16+PTR
            swi_info x6        (8+PTR+4+4)*6
            resource_info      <- offset computed below
              .res_data_mem*   offset 0 within resource_info

        Returns (res_data_ptr, drv_client_id) or (None, None) on failure.
        """
        PTR = self.ramdump.sizeof('void *') or 8

        # Read drv_client_id
        drv_client_id_off = self._hfi_get_offset(
            'struct hfi_core_drv_data', 'drv_client_id', None)
        if drv_client_id_off is None:
            log_fn("WARNING: cannot get drv_client_id offset, using client_id={}"
                   .format(client_id))
            drv_client_id = client_id
        else:
            drv_client_id = self.ramdump.read_u32(drv_data_ptr + drv_client_id_off)

        # client_data[] array offset in hfi_core_drv_data
        client_data_off = self._hfi_get_offset(
            'struct hfi_core_drv_data', 'client_data', None)
        if client_data_off is None:
            log_fn("WARNING: 'struct hfi_core_drv_data' not in symbols")
            return None, drv_client_id

        # client_data element size
        client_elem_size = self._hfi_get_size('struct client_data', None)

        # resource_info offset within client_data
        res_info_off = self._hfi_get_offset(
            'struct client_data', 'resource_info', None)

        # res_data_mem offset within hfi_core_resource_info
        res_data_mem_off = self._hfi_get_offset(
            'struct hfi_core_resource_info', 'res_data_mem', None)

        if None in (client_elem_size, res_info_off, res_data_mem_off):
            log_fn("WARNING: hfi_core.ko struct symbols unavailable, "
                   "using manual offsets from hfi_core.h")
            # Manual computation (64-bit):
            # hfi_core_swi_info: phys_addr_t(8) + iomem*(PTR) + u32(4) + pad(4)
            SWI_SIZE = 8 + PTR + 4 + 4
            # hfi_core_ipc_info: enum(4)+pad(4)+void*(PTR)+u32(4)+pad(4)
            IPC_SIZE = 4 + 4 + PTR + 4 + 4
            # resource_info offset in client_data:
            # PTR + 8 + PTR + 8 + PTR + PTR + IPC_SIZE + SWI_SIZE*6
            res_info_off = PTR + 8 + PTR + 8 + PTR + PTR + IPC_SIZE + SWI_SIZE * 6
            res_data_mem_off = 0   # first field of hfi_core_resource_info

            # client_data element size approximation
            # resource_info size: PTR*3 + 1+1+6 + PTR + 4+4 + PTR = PTR*5 + 24
            RES_INFO_SIZE = PTR * 5 + 24
            # queue_info: PTR + 4 + 4
            QUEUE_INFO_SIZE = PTR + 4 + 4
            # remaining: bool(1)+pad(7)+ptr*3+atomic(4)+pad(4)
            TAIL_SIZE = 8 + PTR * 3 + 8
            raw_size = res_info_off + RES_INFO_SIZE + QUEUE_INFO_SIZE + TAIL_SIZE
            client_elem_size = ((raw_size + PTR - 1) // PTR) * PTR

        client_elem_addr = (drv_data_ptr + client_data_off
                            + client_id * client_elem_size)
        res_data_ptr = self.ramdump.read_pointer(
            client_elem_addr + res_info_off + res_data_mem_off)
        return res_data_ptr, drv_client_id

