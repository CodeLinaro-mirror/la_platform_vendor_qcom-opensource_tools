# =============================================================================
# HFI COMMAND BUFFER STRUCTURE REFERENCE
# =============================================================================
#
# Every HFI command buffer sent from HLOS (Linux display driver) to display-FW
# (DCP) starts with one hfi_header followed by one or more hfi_packet records.
# Its slot size comes from queue metadata (currently 4 KB). Understanding these
# two structures is the key to reading any HFI dump files produced by this parser.
#
# All values are little-endian 32-bit words (u32).
#
# -----------------------------------------------------------------------------
# struct hfi_header  (32 bytes = 8 x u32)
# Source: display-drivers/msm/hfi/hfi_packet.h
# -----------------------------------------------------------------------------
#
#  Word  Byte-off  Field            Description
#  ----  --------  ---------------  -------------------------------------------
#   0      0       cmd_buff_info    Packed field:
#                                     bits [23: 0] total_size  — total bytes
#                                       used in this buffer (header + all
#                                       packets).  Parser stops reading at this
#                                       offset.
#                                     bits [31:24] buff_type   — what kind of
#                                       commands this buffer carries:
#                                         1 = SYSTEM
#                                         2 = DEVICE
#                                         3 = DISPLAY  (most common)
#                                         4 = DEBUG
#                                         5 = VIRTUALIZATION
#   1      4       dev_obj_id       Packed field:
#                                     bits [15: 0] device_id   — hardware
#                                       device index (usually 0).
#                                     bits [31:16] object_id   — identifies the
#                                       target display/thread.  Bits [7:0] of
#                                       object_id are the display_id (0, 1 …).
#                                       Bits [15:8] of object_id are
#                                       cmd_buff_flags:
#                                         bit 0 (0x01) = ASYNC
#                                         bit 1 (0x02) = NO_WAIT
#                                         bit 2 (0x04) = CHAINED — this buffer
#                                           is a continuation of the previous
#                                           one in a chained sequence (set when
#                                           a 4 KB page was full and a new page
#                                           was allocated to hold the overflow).
#   2      8       timestamp_hi     High 32 bits of a 64-bit kernel timestamp
#                                   (ktime_get() nanoseconds, upper word).
#   3     12       timestamp_lo     Low 32 bits of the same timestamp.
#                                   Full timestamp = (timestamp_hi << 32) |
#                                   timestamp_lo.
#   4     16       header_id        Unique ID for this buffer, generated by
#                                   HLOS.  DCP echoes it back in the response
#                                   so HLOS can match responses to requests.
#                                   Encodes client_id in bits [7:0].
#   5     20       reserved[0]      Reserved, always 0.
#   6     24       reserved[1]      Reserved, always 0.
#   7     28       num_packets      Number of hfi_packet records that follow
#                                   this header in the buffer.
#
# -----------------------------------------------------------------------------
# struct hfi_packet  (32 bytes = 8 x u32)
# Source: display-drivers/msm/hfi/hfi_packet.h
# -----------------------------------------------------------------------------
#
#  Word  Byte-off  Field            Description
#  ----  --------  ---------------  -------------------------------------------
#   0      0       payload_info     Packed field:
#                                     bits [20: 0] pkt_size    — total size of
#                                       this packet in bytes, INCLUDING this
#                                       32-byte header.  Payload size =
#                                       pkt_size - 32.
#                                     bits [31:21] payload_type — how to
#                                       interpret the payload bytes:
#                                         0 = NONE      (no payload)
#                                         1 = U32       (single 32-bit value)
#                                         2 = U32_ARRAY (array of u32; for
#                                               SET_PROPERTY this is a KV list)
#                                         3 = U64       (single 64-bit value)
#                                         4 = U64_ARRAY (array of u64)
#                                         5 = BLOB      (raw binary blob)
#   1      4       cmd              Command ID — what operation this packet
#                                   requests.  Common values:
#                                     0x02000001 = SET_PROPERTY
#                                     0x02000002 = GET_PROPERTY
#                                     0x02000003 = FRAME_TRIGGER
#                                     0x02000006 = DISPLAY_ENABLE
#                                     0x02000008 = DISPLAY_DISABLE
#                                     0x0200001E = BOUNDARY_MARKER (sentinel
#                                       written at end of a full page before
#                                       chaining; FW stops parsing on this)
#   2      8       flags            TX flag bitmask (set by HLOS):
#                                     bit 0 (0x1) = INTR_REQUIRED
#                                     bit 1 (0x2) = RESPONSE_REQUIRED
#                                     bit 2 (0x4) = NON_DISCARDABLE
#   3     12       id               Target object ID for this packet:
#                                     bits [15:0] — display_id for display
#                                       commands, layer_id for layer/plane
#                                       commands.
#                                     bits [31:16] — reserved.
#   4     16       packet_id        Unique packet sequence number assigned by
#                                   HLOS.  Used to match GET_PROPERTY responses
#                                   back to the original request.
#   5     20       reserved[0]      Reserved, always 0.
#   6     24       reserved[1]      Reserved, always 0.
#   7     28       reserved[2]      Reserved, always 0.
#
# Immediately after the 32-byte hfi_packet header come (pkt_size - 32) bytes
# of payload.  For SET_PROPERTY (cmd=0x02000001, payload_type=U32_ARRAY) the
# payload is a KV list:
#   u32  num_props
#   for each property:
#     u32  key  = prop_id[19:0] | version[23:20] | dsize_dwords[31:24]
#     u32  value[dsize_dwords]
#
# For FRAME_TRIGGER (cmd=0x02000003) the payload is a single u32:
#   u32  commit_flag  (1=HFI_VALIDATE, 2=HFI_COMMIT)
#
# =============================================================================


