    def write_hfi_commit_index(self, out):
        """
        Write a derived index of display commits into the queue-packet report.

        Why cmd_buf_list is empty at crash time
        ----------------------------------------
        After hfi_adapter_set_cmd_buf() sends a frame, hfi_adapter_release_cmd_buf()
        calls _hfi_clear_buffer() which:
          1. Sets is_released = true
          2. list_del_init(&buffer->node)  -- removes from cmd_buf_list
          3. memset(&buffer->buf, 0, ...)  -- zeros pbuf_vaddr in the descriptor

        So cmd_buf_list is always empty between frames.  The packet data however
        still lives in the pre-allocated TX buffer pages managed by hfi_core:

          hfi_core_drv_data (global 'drv_data')
            .client_data[drv_client_id]
              .resource_info.res_data_mem -> hfi_resource_data
                .vitq_res.q_mem[i]
                  .tx_buff_mem            -> hfi_memory_alloc_info
                    .cpu_va               -- base VA of all TX slots for queue i
                    .size_allocated       -- tx_elements * tx_buff_size_bytes

        Each TX buffer slot holds one command buffer. We scan each bounded slot
        across all queues and collect those that contain
        HFI_COMMAND_DISPLAY_FRAME_TRIGGER (0x02000003).  The most recent one
        is identified by the highest header timestamp.

        The detailed HFI headers and packets are emitted later by
        parse_hfi_queue_packets(); this index only links each commit to them.
        """
        import struct as _struct

        HFI_HDR_SIZE = 32
        HFI_PKT_HDR_SIZE = 32
        HFI_CMD_FRAME_TRIGGER = 0x02000003

        print_out_str("Starting write_hfi_commit_index")

        SEP = '=' * 100
        out.write("HFI DISPLAY COMMIT INDEX\n")
        out.write("Source: hfi_core TX buffer pages scanned for "
                  "HFI_COMMAND_DISPLAY_FRAME_TRIGGER (0x02000003)\n")
        out.write("Note: cmd_buf_list is empty after frame send — "
                  "pbuf_vaddr is cleared by _hfi_clear_buffer() on release.\n")
        out.write("      TX pages from hfi_core vitq_res.q_mem[].tx_buff_mem "
                  "retain the last written data.\n")
        out.write(SEP + "\n\n")

        # ------------------------------------------------------------------
        # Locate drv_data (global struct hfi_core_drv_data * in hfi_core.c)
        # ------------------------------------------------------------------
        drv_data_sym = self.ramdump.address_of('drv_data')
        if not drv_data_sym:
            out.write("ERROR: kernel symbol 'drv_data' not found.\n")
            print_out_str("write_hfi_commit_index: 'drv_data' not found")
            return

        drv_data_ptr = self.ramdump.read_pointer(drv_data_sym)
        if not drv_data_ptr:
            out.write("ERROR: 'drv_data' pointer is NULL.\n")
            return

        out.write("drv_data @ 0x{:x}\n\n".format(drv_data_ptr))

        # ------------------------------------------------------------------
        # Read drv_client_id and resolve res_data_mem via shared helper
        # (handles missing hfi_core.ko DWARF symbols gracefully)
        # ------------------------------------------------------------------
        def _log(msg):
            out.write(msg + "\n")

        # Read drv_client_id first (1=HLOS, 2=TVM) — only that slot is initialised
        drv_client_id = None
        try:
            drv_client_id_off = self.ramdump.field_offset(
                'struct hfi_core_drv_data', 'drv_client_id')
            if drv_client_id_off is not None:
                drv_client_id = self.ramdump.read_u32(
                    drv_data_ptr + drv_client_id_off)
        except Exception as ex:
            out.write("WARNING: could not read drv_client_id: {}\n".format(ex))

        _active_client_id = (drv_client_id
                             if (drv_client_id and 1 <= drv_client_id < 4)
                             else 1)
        out.write("drv_client_id={} active_client_id={}\n\n".format(
            drv_client_id, _active_client_id))

        try:
            res_data_ptr, _ = self._hfi_resolve_res_data_ptr(
                drv_data_ptr, _active_client_id, _log)
        except Exception as ex:
            out.write("ERROR: cannot resolve res_data_mem: {}\n".format(ex))
            return

        if not res_data_ptr:
            out.write("ERROR: res_data_mem is NULL.\n")
            return

        out.write("drv_client_id={} res_data @ 0x{:x}\n\n".format(
            drv_client_id, res_data_ptr))

        # ------------------------------------------------------------------
        # Resolve queue offsets via shared helper
        # ------------------------------------------------------------------
        off = self._hfi_resolve_queue_offsets()
        vitq_res_off = off['vitq_res_off']
        num_q_off = off['num_q_off']
        q_mem_off = off['q_mem_off']
        q_elem_size = off['q_elem_size']
        q_info_off = off['q_info_off']
        prio_off = off['prio_off']
        tx_elements_off = off['tx_elements_off']
        tx_buf_sz_off = off['tx_buf_sz_off']
        tx_buff_off = off['tx_buff_off']
        cpu_va_off = off['cpu_va_off']
        size_alloc_off = off['size_alloc_off']

        try:
            num_queues = self.ramdump.read_u32(
                res_data_ptr + vitq_res_off + num_q_off)
        except Exception as ex:
            out.write("ERROR: cannot read num_queues: {}\n".format(ex))
            return

        PRIO_NAMES = {0: 'PRIO_0(HIGHEST_ASYNC)', 1: 'PRIO_1(HIGH)',
                      2: 'PRIO_2(MEDIUM)', 3: 'PRIO_3(EVENTS)'}

        # Collect all TX pages that contain FRAME_TRIGGER
        # Each entry: (timestamp_u64, queue_idx, priority, page_idx, page_va, buf_data)
        frame_trigger_pages = []

        q_mem_base = res_data_ptr + vitq_res_off + q_mem_off

        if not num_queues:
            out.write("Invalid num_queues=0\n")
            return
        if num_queues > self.MAX_NUM_QUEUES:
            out.write("num_queues={} exceeds maximum {}; parsing {} queues\n".format(
                num_queues, self.MAX_NUM_QUEUES, self.MAX_NUM_QUEUES))
            num_queues = self.MAX_NUM_QUEUES

        for qi in range(num_queues):
            q_elem_addr = q_mem_base + qi * q_elem_size
            try:
                priority = self.ramdump.read_u32(q_elem_addr + q_info_off + prio_off)
                # Read per-buffer size and element count directly from ramdump.
                tx_buf_size = self.ramdump.read_u32(
                    q_elem_addr + q_info_off + tx_buf_sz_off)
                tx_elements = self.ramdump.read_u32(
                    q_elem_addr + q_info_off + tx_elements_off) or 0
                tx_cpu_va = self.ramdump.read_pointer(
                    q_elem_addr + tx_buff_off + cpu_va_off)
                tx_size = self.ramdump.read_u64(
                    q_elem_addr + tx_buff_off + size_alloc_off)
            except Exception as ex:
                out.write("Queue[{}] TX metadata read failed: {}\n".format(
                    qi, ex))
                continue

            num_pages, bound_note = self._hfi_queue_slot_count(
                tx_elements, tx_buf_size, tx_size)
            if bound_note:
                out.write("Queue[{}] TX buffer bounds: {}\n".format(
                    qi, bound_note))
            if not tx_cpu_va or not num_pages:
                continue

            for page_idx in range(num_pages):
                page_va = tx_cpu_va + page_idx * tx_buf_size

                # Read one TX buffer slot. get_bin_data() translates each
                # virtual page independently, so this also works for vmapped
                # allocations backed by physically scattered pages.
                try:
                    page_data = bytes(self.ramdump.get_bin_data(
                        page_va, tx_buf_size))
                    if len(page_data) != tx_buf_size:
                        raise ValueError("short TX buffer read: {} of {} bytes".format(
                            len(page_data), tx_buf_size))
                except Exception as bulk_ex:
                    # Keep the per-word read as a fallback for partial or
                    # otherwise unreadable bulk mappings.
                    try:
                        page_data = bytearray()
                        for _off in range(0, tx_buf_size, 4):
                            val = self.ramdump.read_u32(page_va + _off)
                            page_data += _struct.pack(
                                '<I', val if val is not None else 0)
                        page_data = bytes(page_data)
                    except Exception as fallback_ex:
                        out.write(
                            "Queue[{}] TX page[{}] read failed: bulk read "
                            "({}); per-word fallback ({})\n".format(
                                qi, page_idx, bulk_ex, fallback_ex))
                        continue

                if len(page_data) < HFI_HDR_SIZE:
                    continue

                # Parse hfi_header
                try:
                    (cmd_buff_info, dev_obj_id, ts_hi, ts_lo,
                     header_id, _r0, _r1, num_packets) = _struct.unpack_from('<IIIIIIII', page_data, 0)
                except _struct.error:
                    continue

                total_sz = cmd_buff_info & 0x00FFFFFF
                buff_type = (cmd_buff_info >> 24) & 0xFF
                obj_id = (dev_obj_id >> 16) & 0xFFFF

                if total_sz < HFI_HDR_SIZE or num_packets == 0:
                    continue

                timestamp = (ts_hi << 32) | ts_lo

                # Scan packets for FRAME_TRIGGER
                has_ft = False
                pkt_off = HFI_HDR_SIZE
                for _ in range(num_packets):
                    if pkt_off + HFI_PKT_HDR_SIZE > min(total_sz, tx_buf_size):
                        break
                    try:
                        (payload_info, cmd, _f, _id, _pid,
                         _r0, _r1, _r2) = _struct.unpack_from(
                            '<IIIIIIII', page_data, pkt_off)
                    except _struct.error:
                        break
                    pkt_size = payload_info & 0x001FFFFF
                    if cmd == HFI_CMD_FRAME_TRIGGER:
                        has_ft = True
                        break
                    if pkt_size < HFI_PKT_HDR_SIZE:
                        break
                    pkt_off += pkt_size

                # Store every valid page so we can reconstruct chains later.
                # Tuple layout: (timestamp, qi, priority, page_idx, page_va,
                #                page_data, header_id, display_id, num_packets,
                #                total_sz, buff_type, has_ft)
                frame_trigger_pages.append(
                    (timestamp, qi, priority, page_idx, page_va, page_data,
                     header_id, obj_id & 0xFF, num_packets, total_sz,
                     buff_type, has_ft))

        # ------------------------------------------------------------------
        # Group collected pages into commit chains.
        #
        # How chaining works in the CURRENT code (no CHAINED flag patch):
        #   - Each buffer in a chain gets its OWN independent header_id from
        #     _create_buffer_id() — there is NO shared ID between chained
        #     buffers.  HFI_CMD_BUFF_FLAG_CHAINED is only in the debug patch
        #     (readme_marker_chained_buf.txt) and never in the running kernel.
        #   - All buffers in a chain share the same obj_id (display_id) and
        #     are allocated from the same TX pool as consecutive slots.
        #   - hfi_core_cmds_tx_buf_send() sends them as an array buff_arr[0..N]
        #     so they occupy consecutive page_idx slots in the TX buffer pool.
        #   - The FRAME_TRIGGER packet is always in the LAST slot of the chain.
        #
        # Strategy — walk backwards from each FRAME_TRIGGER page:
        #   1. Find all pages that contain FRAME_TRIGGER (chain tails).
        #   2. For each tail at (qi, page_idx), walk backwards through
        #      page_idx-1, page_idx-2, ... collecting pages from the same
        #      queue that have the same display_id and no FRAME_TRIGGER,
        #      stopping when a gap or different display_id is found.
        #   3. Sort chains by tail timestamp (most recent commit first).
        # ------------------------------------------------------------------

        # Build a fast lookup: (qi, page_idx) -> page entry
        page_lookup = {}
        for entry in frame_trigger_pages:
            (ts, qi, prio, pidx, pva, pdata, hid, did, npkts, tsz, btype, has_ft) = entry
            page_lookup[(qi, pidx)] = entry

        ft_pages = [e for e in frame_trigger_pages if e[11]]  # has_ft at index 11

        if not ft_pages:
            out.write("No TX pages containing HFI_COMMAND_DISPLAY_FRAME_TRIGGER "
                      "found across {} queue(s).\n".format(num_queues))
            out.write("The underlying memory may have been reused or overwritten.\n")
            out.write(SEP + "\n\n")
            print_out_str("write_hfi_commit_index: no FRAME_TRIGGER pages found")
            return

        # header_id layout (from _create_buffer_id() in hfi_adapter.c):
        #   bits [ 7: 0] = client_id  (constant per session)
        #   bits [31: 8] = unique_id_counter  (increments by 1 per buffer allocated)
        #
        # Chained buffers are allocated back-to-back so their unique_id_counter
        # values are consecutive integers.  This is the most reliable way to
        # identify a chain without the CHAINED flag patch.
        def _unique_counter(hid):
            return (hid >> 8) & 0xFFFFFF

        commits = []
        for tail in ft_pages:
            (ts, qi, prio, pidx, pva, pdata, hid, did, npkts, tsz, btype, _) = tail
            tail_counter = _unique_counter(hid)
            client_id = hid & 0xFF

            # Walk backwards: collect slots whose unique_id_counter is exactly
            # (tail_counter - 1), (tail_counter - 2), ... and share the same
            # client_id and display_id.  Stop as soon as the counter is not
            # consecutive or the slot belongs to a different commit.
            chain = [tail]
            expected_counter = tail_counter - 1
            prev_idx = pidx - 1
            while prev_idx >= 0 and expected_counter > 0:
                prev = page_lookup.get((qi, prev_idx))
                if prev is None:
                    break
                (pts, pqi, pprio, ppidx, ppva, ppdata,
                 phid, pdid, pnpkts, ptsz, pbtype, phas_ft) = prev
                # Must be same client_id, same display_id, no FRAME_TRIGGER,
                # and unique_id_counter must be exactly one less than expected
                if (pdid != did or phas_ft or
                        (phid & 0xFF) != client_id or
                        _unique_counter(phid) != expected_counter):
                    break
                chain.insert(0, prev)
                expected_counter -= 1
                prev_idx -= 1
            commits.append((ts, qi, prio, hid, did, chain))

        # Sort commits by timestamp descending — most recent first
        commits.sort(key=lambda c: c[0], reverse=True)

        out.write("Found {} commit(s) with FRAME_TRIGGER across all queues.\n".format(
            len(commits)))
        out.write("Sorted by timestamp (most recent first).\n\n")

        for rank, (timestamp, qi, priority, header_id, display_id, chain) in enumerate(commits):

            prio_name = PRIO_NAMES.get(priority, 'PRIO_{}'.format(priority))

            out.write("{}\n".format(SEP))
            out.write("COMMIT #{} {}\n".format(
                rank + 1, "(MOST RECENT)" if rank == 0 else ""))
            out.write("  Queue[{}]  {}  display_id={}  "
                      "timestamp=0x{:016x}  buffers_in_chain={}\n".format(
                          qi, prio_name, display_id, timestamp, len(chain)))
            out.write("  Note: chained buffers identified by consecutive "
                      "unique_id_counter (header_id bits[31:8]) + same "
                      "client_id and display_id.\n")
            out.write("{}\n\n".format(SEP))

            for buf_idx, (ts_b, qi_b, prio_b, page_idx, page_va, page_data,
                          hid_b, did_b, num_packets, total_sz,
                          buff_type, has_ft_b) in enumerate(chain):

                bt_name = self.HFI_CMD_BUFF_TYPE_NAMES.get(
                    buff_type, '0x{:x}'.format(buff_type))
                role = "FRAME_TRIGGER (tail)" if has_ft_b else "chained predecessor"

                out.write("  --- BUFFER [{}/{}] {}  page_idx={}  page_va=0x{:x}"
                          "  header_id=0x{:08x}  unique_id_counter={}\n".format(
                              buf_idx + 1, len(chain), role, page_idx, page_va,
                              hid_b, _unique_counter(hid_b)))
                try:
                    _page_phys = self.ramdump.virt_to_phys(page_va)
                except Exception as ex:
                    _page_phys = None
                    out.write("    WARNING: cannot translate page VA 0x{:x}: {}\n".format(
                        page_va, ex))
                out.write("    page_phys  : {}\n".format(
                    "0x{:x}".format(_page_phys) if _page_phys else "N/A"))
                out.write("    hdr_va     : 0x{:x}  (ramdump: rd 0x{:x} 32)\n".format(
                    page_va, page_va))

        out.write(SEP + "\n\n")
        print_out_str("write_hfi_commit_index: found {} commit(s)".format(
            len(commits)))

    @_close_output_file
    def parse_hfi_queue_packets(self):
        """
        Dump and decode all HFI packets from the Tx and Rx virtio queue
        buffers for every priority queue of every client.

        Memory walk (from hfi_core_probe.c / hfi_if_abstraction.h):

          hfi_core_drv_data  (global, stored as platform drvdata)
            .client_data[client_id]
              .resource_info
                .res_data_mem  ->  struct hfi_resource_data
                  .vitq_res
                    .num_queues
                    .q_mem[i]  ->  struct hfi_res_vq_queue_data
                      .q_info.priority
                      .tx_buff_mem  ->  struct hfi_memory_alloc_info
                          .cpu_va          (kernel VA of contiguous buffer)
                          .size_allocated  (tx_elements * tx_buff_size_bytes)
                      .rx_buff_mem  ->  struct hfi_memory_alloc_info
                          .cpu_va
                          .size_allocated  (rx_elements * rx_buff_size_bytes)

        Each buffer slot holds one hfi_header + N hfi_packets. Slots with an
        all-zero header (total_size == 0) are skipped.

        Output: display_info/dcp_hfi_queue_packets.txt
        """
        import struct as _struct

        HFI_HDR_SIZE = 32   # sizeof(struct hfi_header)
        HFI_PKT_HDR_SIZE = 32   # sizeof(struct hfi_packet)

        PRIO_NAMES = {0: 'PRIO_0(HIGHEST_ASYNC)', 1: 'PRIO_1(HIGH)',
                      2: 'PRIO_2(MEDIUM)', 3: 'PRIO_3(EVENTS)'}
        CLIENT_NAMES = {1: 'CLIENT_0(HLOS)', 2: 'CLIENT_1(TVM)',
                        3: 'CLIENT_LOOPBACK_DCP'}

        print_out_str("Starting parse_hfi_queue_packets")

        try:
            out = self.ramdump.open_file('display_info/dcp_hfi_queue_packets.txt', 'w')
            self.outfile = out
        except Exception as ex:
            print_out_str("parse_hfi_queue_packets: cannot open output: {}".format(ex))
            return

        SEP = '=' * 100
        SEP2 = '-' * 80

        out.write("HFI VIRTIO QUEUE PACKET DUMP\n")
        out.write("Source: hfi_core_drv_data -> client_data[].resource_info"
                  ".res_data_mem -> vitq_res.q_mem[].tx/rx_buff_mem\n")
        out.write(SEP + "\n\n")

        self.write_hfi_commit_index(out)
        out.write("HFI VIRTIO QUEUE PACKET DETAILS\n")
        out.write(SEP + "\n\n")

        # ------------------------------------------------------------------
        # 1. Locate hfi_core_drv_data
        #
        #    hfi_core.c declares a non-static global:
        #        struct hfi_core_drv_data *drv_data;
        #    address_of('drv_data') gives the address of this pointer.
        #    read_pointer() dereferences it to get the struct address.
        # ------------------------------------------------------------------
        drv_data_sym = self.ramdump.address_of('drv_data')
        if not drv_data_sym:
            out.write("ERROR: kernel symbol 'drv_data' not found.\n")
            out.write("       Ensure hfi_core.ko symbols are loaded.\n")
            out.close()
            print_out_str("parse_hfi_queue_packets: symbol 'drv_data' not found")
            return

        drv_data_ptr = self.ramdump.read_pointer(drv_data_sym)
        if not drv_data_ptr:
            out.write("ERROR: 'drv_data' pointer is NULL.\n")
            out.close()
            print_out_str("parse_hfi_queue_packets: drv_data is NULL")
            return

        out.write("drv_data (struct hfi_core_drv_data *) @ 0x{:x}\n\n".format(
            drv_data_ptr))

        # ------------------------------------------------------------------
        # 2. Read drv_client_id from drv_data->drv_client_id
        #
        #    The probe reads 'qcom,hfi-client-id' from DT and stores it in
        #    drv_data->drv_client_id.  Only that one client slot is
        #    initialised.  We iterate all valid slots (1..3) but only the
        #    one matching drv_client_id will have non-NULL res_data_mem.
        # ------------------------------------------------------------------
        try:
            drv_client_id_offset = self.ramdump.field_offset(
                'struct hfi_core_drv_data', 'drv_client_id')
            drv_client_id = self.ramdump.read_u32(
                drv_data_ptr + drv_client_id_offset)
        except Exception as ex:
            drv_client_id = None
            out.write("WARNING: could not read drv_client_id: {}\n".format(ex))

        out.write("drv_client_id = {}\n\n".format(
            drv_client_id if drv_client_id is not None else 'unknown'))

        # Only drv_client_id is initialised by the probe — iterate that slot only.
        # HFI_CORE_CLIENT_ID_0=1 (HLOS), CLIENT_ID_1=2 (TVM)
        if drv_client_id is None or drv_client_id < 1 or drv_client_id >= 4:
            out.write("WARNING: invalid drv_client_id={}, defaulting to 1\n\n"
                      .format(drv_client_id))
            drv_client_id = 1

        found_any = False

        for client_id in [drv_client_id]:
            client_name = CLIENT_NAMES.get(client_id, 'CLIENT_{}'.format(client_id))

            # Resolve res_data_mem via shared helper
            # (handles missing hfi_core.ko DWARF symbols gracefully)
            def _log_client(msg):
                out.write("[{}] {}\n".format(client_name, msg))
            try:
                res_data_ptr, _ = self._hfi_resolve_res_data_ptr(
                    drv_data_ptr, client_id, _log_client)
            except Exception as ex:
                out.write("[{}] Could not read resource_info.res_data_mem: {}\n\n"
                          .format(client_name, ex))
                continue

            if not res_data_ptr:
                out.write("[{}] resource_info.res_data_mem is NULL — skipping\n\n".format(
                    client_name))
                continue

            # Resolve queue offsets via shared helper
            off = self._hfi_resolve_queue_offsets()
            vitq_res_off = off['vitq_res_off']
            num_q_off = off['num_q_off']
            q_mem_off = off['q_mem_off']
            q_elem_size = off['q_elem_size']
            q_info_off = off['q_info_off']
            prio_off = off['prio_off']
            tx_elements_off = off['tx_elements_off']
            rx_elements_off = off['rx_elements_off']
            tx_buf_sz_off = off['tx_buf_sz_off']
            rx_buf_sz_off = off['rx_buf_sz_off']
            tx_buff_off = off['tx_buff_off']
            rx_buff_off = off['rx_buff_off']
            cpu_va_off = off['cpu_va_off']
            size_alloc_off = off['size_alloc_off']

            try:
                num_queues = self.ramdump.read_u32(
                    res_data_ptr + vitq_res_off + num_q_off)
            except Exception as ex:
                out.write("[{}] Could not read vitq_res.num_queues: {}\n\n".format(
                    client_name, ex))
                continue

            if not num_queues:
                out.write("[{}] num_queues=0 — invalid, skipping\n\n".format(
                    client_name))
                continue
            if num_queues > self.MAX_NUM_QUEUES:
                out.write("[{}] num_queues={} exceeds maximum {}; parsing {} queues\n\n".format(
                    client_name, num_queues, self.MAX_NUM_QUEUES,
                    self.MAX_NUM_QUEUES))
                num_queues = self.MAX_NUM_QUEUES

            out.write("CLIENT: {}  num_queues={}\n".format(
                client_name, num_queues))
            out.write("  (struct hfi_core_drv_data *)            @ 0x{:x}\n".format(
                drv_data_ptr))
            out.write("  (struct hfi_resource_data *) res_data   @ 0x{:x}\n".format(
                res_data_ptr))
            out.write("  (struct hfi_virtq_res *)     vitq_res   @ 0x{:x}\n".format(
                res_data_ptr + vitq_res_off))
            out.write("  (struct hfi_res_vq_queue_data *) q_mem  @ 0x{:x}  [elem_size={}]\n".format(
                res_data_ptr + vitq_res_off + q_mem_off, q_elem_size))
            out.write("{}\n\n".format(SEP))

            q_mem_base = res_data_ptr + vitq_res_off + q_mem_off

            for qi in range(num_queues):
                q_elem_addr = q_mem_base + qi * q_elem_size

                try:
                    priority = self.ramdump.read_u32(
                        q_elem_addr + q_info_off + prio_off)
                    prio_name = PRIO_NAMES.get(priority,
                                               'PRIO_{}'.format(priority))

                    tx_buf_size = self.ramdump.read_u32(
                        q_elem_addr + q_info_off + tx_buf_sz_off)
                    rx_buf_size = self.ramdump.read_u32(
                        q_elem_addr + q_info_off + rx_buf_sz_off)
                    tx_elements = self.ramdump.read_u32(
                        q_elem_addr + q_info_off + tx_elements_off) or 0
                    rx_elements = self.ramdump.read_u32(
                        q_elem_addr + q_info_off + rx_elements_off) or 0

                    tx_cpu_va = self.ramdump.read_pointer(
                        q_elem_addr + tx_buff_off + cpu_va_off)
                    tx_size = self.ramdump.read_u64(
                        q_elem_addr + tx_buff_off + size_alloc_off)

                    rx_cpu_va = self.ramdump.read_pointer(
                        q_elem_addr + rx_buff_off + cpu_va_off)
                    rx_size = self.ramdump.read_u64(
                        q_elem_addr + rx_buff_off + size_alloc_off)
                except Exception as ex:
                    out.write("  [Q{}] Could not read queue metadata: {}\n\n".format(
                        qi, ex))
                    continue

                out.write("  {}\n".format(SEP2))
                out.write("  QUEUE[{}]  {}\n".format(qi, prio_name))
                out.write("    (struct hfi_res_vq_queue_data *)  @ 0x{:x}\n".format(
                    q_elem_addr))
                out.write("    (struct hfi_virt_queue_data *)    q_info @ 0x{:x}\n"
                          "      tx_elements={}  tx_buff_size_bytes={}  "
                          "rx_elements={}  rx_buff_size_bytes={}\n".format(
                              q_elem_addr + q_info_off,
                              tx_elements, tx_buf_size, rx_elements, rx_buf_size))
                out.write("    (struct hfi_memory_alloc_info *)  tx_buff_mem @ 0x{:x}"
                          "  cpu_va=0x{:x}  size_allocated={}\n".format(
                              q_elem_addr + tx_buff_off, tx_cpu_va or 0, tx_size))
                out.write("    (struct hfi_memory_alloc_info *)  rx_buff_mem @ 0x{:x}"
                          "  cpu_va=0x{:x}  size_allocated={}\n".format(
                              q_elem_addr + rx_buff_off, rx_cpu_va or 0, rx_size))
                out.write("  {}\n\n".format(SEP2))

                # --------------------------------------------------------------
                # 5. Dump each bounded slot from Tx and Rx buffers
                # --------------------------------------------------------------
                for direction, cpu_va, total_size in (
                        ('TX', tx_cpu_va, tx_size),
                        ('RX', rx_cpu_va, rx_size)):

                    buf_size = tx_buf_size if direction == 'TX' else rx_buf_size
                    n_elem = tx_elements if direction == 'TX' else rx_elements
                    num_pages, bound_note = self._hfi_queue_slot_count(
                        n_elem, buf_size, total_size)
                    if bound_note:
                        out.write("    [{} buffer] bounds: {}\n".format(
                            direction, bound_note))
                    if not cpu_va or not num_pages:
                        out.write("    [{} buffer] NULL, invalid, or zero size — skipped\n\n".format(
                            direction))
                        continue

                    out.write("    [{} buffer]  (u8 *)0x{:x}  "
                              "size_allocated={}  elements={}  buf_size_bytes={}\n".format(
                                  direction, cpu_va, total_size, num_pages, buf_size))

                    pages_with_data = 0
                    for page_idx in range(num_pages):
                        page_va = cpu_va + page_idx * buf_size

                        # get_bin_data() translates each virtual page separately,
                        # which is required for vmapped scatter allocations.
                        try:
                            page_data = bytes(self.ramdump.get_bin_data(
                                page_va, buf_size))
                            if len(page_data) != buf_size:
                                raise ValueError(
                                    "short buffer read: {} of {} bytes".format(
                                        len(page_data), buf_size))
                        except Exception as bulk_ex:
                            try:
                                page_data = bytearray()
                                for off in range(0, buf_size, 4):
                                    val = self.ramdump.read_u32(page_va + off)
                                    if val is None:
                                        val = 0
                                    page_data += _struct.pack('<I', val)
                                page_data = bytes(page_data)
                            except Exception as ex:
                                out.write(
                                    "      [page {}] read error: bulk read "
                                    "({}); per-word fallback ({})\n".format(
                                        page_idx, bulk_ex, ex))
                                continue

                        if not page_data or len(page_data) < HFI_HDR_SIZE:
                            continue

                        # Parse hfi_header
                        try:
                            (cmd_buff_info, dev_obj_id, ts_hi, ts_lo,
                             header_id, _r0, _r1, num_packets) = _struct.unpack_from('<IIIIIIII', page_data, 0)
                        except _struct.error:
                            continue

                        total_sz = cmd_buff_info & 0x00FFFFFF
                        buff_type = (cmd_buff_info >> 24) & 0xFF
                        # object_id is upper u16 of word[1] (hfi_packet.h)
                        display_id = (dev_obj_id >> 16) & 0xFFFF
                        unique_id_counter = (header_id >> 8) & 0xFFFFFF

                        # Skip empty / uninitialised pages
                        if total_sz < HFI_HDR_SIZE or num_packets == 0:
                            continue
                        if total_sz > buf_size:
                            total_sz = buf_size

                        pages_with_data += 1
                        buff_type_name = self.HFI_CMD_BUFF_TYPE_NAMES.get(
                            buff_type, '0x{:x}'.format(buff_type))

                        try:
                            _page_phys = self.ramdump.virt_to_phys(page_va)
                        except Exception as ex:
                            _page_phys = None
                            out.write(
                                "      WARNING: cannot translate page VA "
                                "0x{:x}: {}\n".format(page_va, ex))
                        _device_id2 = dev_obj_id & 0xFFFF
                        _object_id2 = (dev_obj_id >> 16) & 0xFFFF
                        _cb_flags2 = (_object_id2 >> 8) & 0xFF
                        _cb_fstrs2 = []
                        if _cb_flags2 & 0x01: _cb_fstrs2.append("ASYNC")
                        if _cb_flags2 & 0x02: _cb_fstrs2.append("NO_WAIT")
                        if _cb_flags2 & 0x04: _cb_fstrs2.append("CHAINED")
                        _cb_fstr2 = "|".join(_cb_fstrs2) if _cb_fstrs2 else "NONE"
                        out.write("\n      [page {:3d}] --- hfi_header @ 0x{:x}  "
                                  "(struct hfi_header *)0x{:x}\n"
                                  "        [w0] cmd_buff_info=0x{:08x}"
                                  "  total_size={}  buff_type={} ({})\n"
                                  "        [w1] dev_obj_id   =0x{:08x}"
                                  "  device_id={}  object_id=0x{:04x}"
                                  "  display_id={}  cb_flags=0x{:02x} ({})\n"
                                  "        [w2] timestamp_hi =0x{:08x}\n"
                                  "        [w3] timestamp_lo =0x{:08x}"
                                  "  full_ts=0x{:016x}\n"
                                  "        [w4] header_id    =0x{:08x}"
                                  "  unique_id_counter={}\n"
                                  "        [w5] reserved[0]  =0x{:08x}\n"
                                  "        [w6] reserved[1]  =0x{:08x}\n"
                                  "        [w7] num_packets  ={}\n"
                                  "        page_va=0x{:x}  page_phys={}"
                                  "  hdr_va=0x{:x}"
                                  "  (ramdump: rd 0x{:x} 32)\n".format(
                                      page_idx, page_va, page_va,
                                      cmd_buff_info, total_sz, buff_type_name, buff_type,
                                      dev_obj_id, _device_id2, _object_id2,
                                      display_id, _cb_flags2, _cb_fstr2,
                                      ts_hi,
                                      ts_lo, (ts_hi << 32) | ts_lo,
                                      header_id,
                                      unique_id_counter,
                                      _r0, _r1,
                                      num_packets,
                                      page_va,
                                      "0x{:x}".format(_page_phys) if _page_phys else "N/A",
                                      page_va, page_va))

                        # Parse packets
                        pkt_off = HFI_HDR_SIZE
                        for pkt_num in range(num_packets):
                            if pkt_off + HFI_PKT_HDR_SIZE > total_sz:
                                break
                            try:
                                (payload_info, cmd, flags, pkt_id_field,
                                 packet_id, _p0, _p1, _p2) = _struct.unpack_from('<IIIIIIII',
                                                                                 page_data, pkt_off)
                            except _struct.error:
                                break

                            pkt_size = payload_info & 0x001FFFFF
                            payload_type = (payload_info >> 21) & 0x7FF
                            layer_id = pkt_id_field & 0xFFFF

                            if pkt_size < HFI_PKT_HDR_SIZE or pkt_off + pkt_size > buf_size:
                                break

                            payload_size = pkt_size - HFI_PKT_HDR_SIZE
                            payload_off = pkt_off + HFI_PKT_HDR_SIZE

                            cmd_name = self._hfi_cmd_name(cmd)
                            flags_str = self._hfi_flags_str(flags)
                            pt_name = self.HFI_PAYLOAD_TYPE_NAMES.get(
                                payload_type, '0x{:x}'.format(payload_type))

                            _pkt_va = page_va + pkt_off
                            _payload_va = page_va + payload_off
                            try:
                                _pkt_phys = self.ramdump.virt_to_phys(_pkt_va)
                            except Exception as ex:
                                _pkt_phys = None
                                out.write(
                                    "        WARNING: cannot translate packet "
                                    "VA 0x{:x}: {}\n".format(_pkt_va, ex))
                            out.write("        --- pkt[{:2d}] @ 0x{:x}  "
                                      "(struct hfi_packet *)0x{:x}\n"
                                      "        [w0] payload_info=0x{:08x}"
                                      "  pkt_size={}  payload_type={} ({})\n"
                                      "        [w1] cmd        =0x{:08x}  ({})\n"
                                      "        [w2] flags      =0x{:08x}  ({})\n"
                                      "        [w3] id         =0x{:08x}"
                                      "  display/layer_id=0x{:04x}\n"
                                      "        [w4] packet_id  =0x{:08x}\n"
                                      "        [w5] reserved[0]=0x{:08x}\n"
                                      "        [w6] reserved[1]=0x{:08x}\n"
                                      "        [w7] reserved[2]=0x{:08x}\n"
                                      "             pkt_va=0x{:x}  pkt_phys={}\n"
                                      "             payload_va=0x{:x}  payload_size={}\n"
                                      "             (ramdump: rd 0x{:x} {})\n".format(
                                          pkt_num, _pkt_va, _pkt_va,
                                          payload_info, pkt_size, pt_name, payload_type,
                                          cmd, cmd_name,
                                          flags, flags_str,
                                          pkt_id_field, layer_id,
                                          packet_id,
                                          _p0, _p1, _p2,
                                          _pkt_va,
                                          "0x{:x}".format(_pkt_phys) if _pkt_phys else "N/A",
                                          _payload_va, payload_size,
                                          _payload_va, payload_size))

                            # Decode KV pairs for SET_PROPERTY
                            if cmd == 0x02000001 and payload_type == 0x2 and payload_size >= 4:
                                kv_props = self._hfi_decode_kv_payload(
                                    page_data, payload_off, payload_size)
                                if kv_props:
                                    out.write("          KV properties ({}):\n".format(
                                        len(kv_props)))
                                    for prop_name, ver, dsize, vals in kv_props:
                                        val_str = ' '.join(
                                            '0x{:08x}'.format(v) for v in vals)
                                        out.write(
                                            "            key={:<55s}  "
                                            "ver={}  dsize={}  "
                                            "value=[{}]\n".format(
                                                prop_name, ver, dsize, val_str))

                            # Decode FRAME_TRIGGER commit flag
                            elif cmd == 0x02000003 and payload_size >= 4:
                                flag_str = self._hfi_decode_frame_trigger_payload(
                                    page_data, payload_off, payload_size)
                                out.write("          commit_flag={}\n".format(
                                    flag_str))

                            # Raw hex for other payloads (capped at 64 bytes)
                            elif payload_size > 0:
                                dump_len = min(payload_size, 64)
                                raw = page_data[payload_off:payload_off + dump_len]
                                hex_str = ' '.join(
                                    '{:02x}'.format(b) for b in bytearray(raw))
                                suffix = '...' if payload_size > 64 else ''
                                out.write("          raw[0:{}]: {}{}\n".format(
                                    dump_len, hex_str, suffix))

                            pkt_off += pkt_size
                            found_any = True

                    out.write("\n    [{} buffer]  pages_with_data={}\n\n".format(
                        direction, pages_with_data))

        if not found_any:
            out.write("\nNo HFI packets found in any queue buffer.\n")

        out.close()
        print_out_str("parse_hfi_queue_packets: wrote display_info/dcp_hfi_queue_packets.txt")

    @_close_output_file
    def dump_hfi_adapter_pool(self):
        """
        Dump every hfi_buffer_pool node that is part of hfi_adapter_t->pool->node
        list, together with the full hfi_cmdbuf_t fields and the decoded HFI
        packets inside each buffer's 4 KB page.

        This is the correct place to look when get_avail_buffer() fails with
        "could not get buffer": all 64 pool nodes have available==0, meaning
        every buffer is either in-flight (submitted to DCP via hfi_core) or
        stuck waiting for a response.

        Memory walk
        -----------
        msm_drm_private  (from 'msm_drm_private' kernel symbol)
          .hfi_priv  ->  struct msm_drm_hfi_private
            .hfi_adapter  ->  struct hfi_adapter_t
              .pool  ->  struct hfi_buffer_pool   (sentinel / head node)
                .node  (list_head)
                  -> link->node ... (MAX_POOL_SIZE=64 real nodes)
                     each struct hfi_buffer_pool:
                       .lock          mutex
                       .node          list_head  { next*, prev* }
                       .available     atomic_t   (1=free, 0=in-use)
                       .buffer_t      hfi_cmdbuf_t
                         .lock        mutex
                         .cmd_type    enum hfi_cmdbuf_type
                         .unique_id   u32
                         .obj_id      u32
                         .size        u32
                         .buf         hfi_core_cmds_buf_desc
                           .pbuf_vaddr  void*  -> 4 KB HFI page
                           .priv_dva    u64    (device VA)
                           .size        size_t
                           .prio_info   enum
                           .priv_idx    u32
                           .flag        u32
                         .node        list_head
                         .cmd_buf_chain list_head
                         .ctx*        hfi_client_t*
                         .pool*       hfi_buffer_pool*
                         .buffer_send_done  atomic_t
                         .is_released bool
                         .waiting_for_rsp   atomic_t
                         .virtq_type  enum hfi_virt_queue_type

        struct hfi_buffer_pool layout (64-bit ARM, hfi_adapter.h):
          mutex  lock              -- MUTEX_SIZE bytes
          list_head node           -- 2*PTR
          atomic_t available       -- 4 bytes + pad(4)
          hfi_cmdbuf_t buffer_t    -- large embedded struct

        struct hfi_cmdbuf_t layout (64-bit ARM, hfi_adapter.h):
          mutex  lock              -- MUTEX_SIZE
          enum   cmd_type          -- 4
          u32    unique_id         -- 4
          u32    obj_id            -- 4
          u32    size              -- 4
          hfi_core_cmds_buf_desc buf:
            void*  pbuf_vaddr      -- PTR
            u64    priv_dva        -- 8
            size_t size            -- PTR (size_t = 8 on 64-bit)
            enum   prio_info       -- 4
            u32    priv_idx        -- 4
            u32    flag            -- 4 + pad(4)
          list_head node           -- 2*PTR
          list_head cmd_buf_chain  -- 2*PTR
          hfi_client_t* ctx        -- PTR
          hfi_buffer_pool* pool    -- PTR
          atomic_t buffer_send_done -- 4
          bool is_released         -- 1 + pad(3)
          atomic_t waiting_for_rsp -- 4
          enum virtq_type          -- 4

        Output: display_info/dcp_hfi_adapter_pool_dump.txt
        """
        import struct as _struct

        HFI_PAGE_SIZE = 4096
        HFI_HDR_SIZE = 32
        HFI_PKT_HDR_SIZE = 32
        MAX_POOL_SIZE = 64

        CMDBUF_TYPE_NAMES = {
            0: 'ATOMIC_CHECK',
            1: 'ATOMIC_COMMIT',
            2: 'DISPLAY_INFO_NO_BLOCK',
            3: 'DISPLAY_INFO_BLOCKING',
            4: 'GET_DEBUG_DATA',
            5: 'DEVICE_INFO',
        }
        VIRTQ_TYPE_NAMES = {0: 'RX', 1: 'TX'}
        PRIO_NAMES = {0: 'PRIO_0(HIGHEST_ASYNC)', 1: 'PRIO_1(HIGH)',
                      2: 'PRIO_2(MEDIUM)', 3: 'PRIO_3(EVENTS)'}

        SEP = '=' * 100
        SEP2 = '-' * 80
        SEP3 = '~' * 60

        print_out_str("Starting dump_hfi_adapter_pool")

        try:
            out = self.ramdump.open_file('display_info/dcp_hfi_adapter_pool_dump.txt', 'w')
            self.outfile = out
        except Exception as ex:
            print_out_str("dump_hfi_adapter_pool: cannot open output: {}".format(ex))
            return

        out.write("HFI ADAPTER POOL DUMP\n")
        out.write("Source: sde_dbg_base -> device -> drm_device -> msm_drm_private -> hfi_priv -> hfi_adapter -> pool -> pool->node\n")
        out.write("Purpose: show all hfi_buffer_pool nodes and their hfi_cmdbuf_t contents.\n")
        out.write("         When get_avail_buffer() fails, all nodes have available==0.\n")
        out.write(SEP + "\n\n")

        PTR = self.ramdump.sizeof('void *') or 8
        MUTEX_SIZE = self.ramdump.sizeof('struct mutex') or 32

        # ------------------------------------------------------------------ #
        # Step 1: Locate msm_drm_private via sde_dbg_base                    #
        #                                                                     #
        # sde_dbg_base is a reliable non-pointer global (struct sde_dbg_base):#
        #   sde_dbg_base.dev  ->  struct device *  (platform_device.dev)     #
        #   device.driver_data  ->  struct drm_device *                      #
        #   drm_device.dev_private  ->  struct msm_drm_private *             #
        #   msm_drm_private.hfi_priv  ->  struct msm_drm_hfi_private *       #
        #   msm_drm_hfi_private.hfi_adapter  ->  struct hfi_adapter_t *      #
        # ------------------------------------------------------------------ #
        sde_dbg_base_sym = self.ramdump.address_of('sde_dbg_base')
        if not sde_dbg_base_sym:
            out.write("ERROR: kernel symbol 'sde_dbg_base' not found.\n")
            out.close()
            print_out_str("dump_hfi_adapter_pool: 'sde_dbg_base' symbol not found")
            return

        # sde_dbg_base is an embedded struct -- its symbol address IS the struct address
        sde_dbg_base_addr = sde_dbg_base_sym
        out.write("(struct sde_dbg_base)        sde_dbg_base @ 0x{:x}\n".format(
            sde_dbg_base_addr))

        # sde_dbg_base.dev  ->  struct device *
        dbg_dev_off = self.ramdump.field_offset('struct sde_dbg_base', 'dev')
        if dbg_dev_off is None:
            out.write("ERROR: cannot resolve sde_dbg_base.dev offset.\n")
            out.close()
            print_out_str("dump_hfi_adapter_pool: cannot resolve sde_dbg_base.dev")
            return
        pdev_dev_ptr = self.ramdump.read_pointer(sde_dbg_base_addr + dbg_dev_off)
        if not pdev_dev_ptr:
            out.write("ERROR: sde_dbg_base.dev is NULL.\n")
            out.close()
            print_out_str("dump_hfi_adapter_pool: sde_dbg_base.dev is NULL")
            return
        out.write("(struct device *)            pdev->dev    @ 0x{:x}\n".format(pdev_dev_ptr))

        # device.driver_data  ->  struct drm_device *
        drv_data_off = self.ramdump.field_offset('struct device', 'driver_data')
        if drv_data_off is None:
            out.write("ERROR: cannot resolve device.driver_data offset.\n")
            out.close()
            print_out_str("dump_hfi_adapter_pool: cannot resolve device.driver_data")
            return
        drm_dev_ptr = self.ramdump.read_pointer(pdev_dev_ptr + drv_data_off)
        if not drm_dev_ptr:
            out.write("ERROR: device->driver_data (drm_device) is NULL.\n")
            out.close()
            print_out_str("dump_hfi_adapter_pool: drm_device is NULL")
            return
        out.write("(struct drm_device *)        drm_dev      @ 0x{:x}\n".format(drm_dev_ptr))

        # drm_device.dev_private  ->  struct msm_drm_private *
        dev_private_off = self.ramdump.field_offset('struct drm_device', 'dev_private')
        if dev_private_off is None:
            out.write("ERROR: cannot resolve drm_device.dev_private offset.\n")
            out.close()
            print_out_str("dump_hfi_adapter_pool: cannot resolve drm_device.dev_private")
            return
        msm_priv_ptr = self.ramdump.read_pointer(drm_dev_ptr + dev_private_off)
        if not msm_priv_ptr:
            out.write("ERROR: drm_device.dev_private (msm_drm_private) is NULL.\n")
            out.close()
            print_out_str("dump_hfi_adapter_pool: msm_drm_private is NULL")
            return
        out.write("(struct msm_drm_private *)   msm_priv     @ 0x{:x}\n".format(msm_priv_ptr))

        # msm_drm_private.hfi_priv  ->  struct msm_drm_hfi_private *
        hfi_priv_off = self.ramdump.field_offset('struct msm_drm_private', 'hfi_priv')
        if hfi_priv_off is None:
            out.write("ERROR: cannot resolve msm_drm_private.hfi_priv offset.\n")
            out.close()
            print_out_str("dump_hfi_adapter_pool: cannot resolve hfi_priv offset")
            return
        hfi_priv_ptr = self.ramdump.read_pointer(msm_priv_ptr + hfi_priv_off)
        if not hfi_priv_ptr:
            out.write("ERROR: msm_drm_private.hfi_priv is NULL.\n")
            out.close()
            print_out_str("dump_hfi_adapter_pool: hfi_priv is NULL")
            return
        out.write("(struct msm_drm_hfi_private *) hfi_priv   @ 0x{:x}\n".format(hfi_priv_ptr))

        # msm_drm_hfi_private.hfi_adapter  ->  struct hfi_adapter_t *
        # struct msm_drm_hfi_private { msm_drm_private* base; hfi_adapter_t* hfi_adapter; ... }
        adapter_off = self.ramdump.field_offset('struct msm_drm_hfi_private', 'hfi_adapter')
        if adapter_off is None:
            adapter_off = PTR   # base* is the only field before hfi_adapter*
        hfi_adapter_ptr = self.ramdump.read_pointer(hfi_priv_ptr + adapter_off)
        if not hfi_adapter_ptr:
            out.write("ERROR: msm_drm_hfi_private.hfi_adapter is NULL.\n")
            out.close()
            print_out_str("dump_hfi_adapter_pool: hfi_adapter_t is NULL")
            return
        out.write("(struct hfi_adapter_t *)     hfi_adapter  @ 0x{:x}\n\n".format(
            hfi_adapter_ptr))

        # ------------------------------------------------------------------ #
        # Step 2: Read hfi_adapter_t fields                                   #
        # ------------------------------------------------------------------ #
        sde_inst_off = self._hfi_get_offset('struct hfi_adapter_t',
                                            'sde_or_vm_instance', 0)
        pool_off = self._hfi_get_offset('struct hfi_adapter_t', 'pool', None)

        if pool_off is None:
            # Manual layout: compute pool offset
            # hfi_adapter_t fields before pool (64-bit ARM):
            #   u32 sde_or_vm_instance (4) + pad(4)
            #   list_head client_list (2*PTR)
            #   hfi_core_cb_ops* cb_ops (PTR)
            #   hfi_core_session* session (PTR)
            #   callback_work cb_cmd_buf_work[64]: each = kthread_work + PTR + int + pad
            #     kthread_work = list_head(2*PTR) + atomic_t(4) + pad(4) + func_ptr(PTR) = 3*PTR+8
            #     callback_work = kthread_work + PTR + 4 + pad(4) = 3*PTR+8 + PTR + 8 = 4*PTR+16
            CB_WORK_SIZE = 4 * PTR + 16
            #   kthread_work cb_ssr_work: 3*PTR+8
            KTHREAD_WORK_SIZE = 3 * PTR + 8
            #   kthread_worker cb_event_worker: list_head(2*PTR)+spinlock(4)+pad(4)+task*(PTR) = 3*PTR+8
            KTHREAD_WORKER_SIZE = 3 * PTR + 8
            #   kthread_worker cb_event_ssr_worker
            #   task_struct* cb_event_worker_thread (PTR)
            #   task_struct* cb_event_worker_ssr_thread (PTR)
            #   kthread_work hfi_thread_priority_work
            #   enum event_type (4) + bool blocking (1) + pad(3)
            #   idr client_ids: varies, use sizeof
            IDR_SIZE = self.ramdump.sizeof('struct idr') or (2 * PTR + 4 + 4)
            pool_off = (8 + 2 * PTR + PTR + PTR
                        + 64 * CB_WORK_SIZE
                        + KTHREAD_WORK_SIZE
                        + 2 * KTHREAD_WORKER_SIZE
                        + 2 * PTR
                        + KTHREAD_WORK_SIZE
                        + 8
                        + IDR_SIZE)
            out.write("WARNING: using manual pool_off={} (DWARF unavailable)\n\n"
                      .format(pool_off))

        sde_inst = self.ramdump.read_u32(hfi_adapter_ptr + sde_inst_off)
        pool_head_ptr = self.ramdump.read_pointer(hfi_adapter_ptr + pool_off)

        out.write("  .sde_or_vm_instance = {} ({})\n".format(
            sde_inst, 'AVM' if sde_inst == 0 else 'TVM' if sde_inst == 1 else '?'))
        out.write("  .pool               = 0x{:x}  "
                  "(struct hfi_buffer_pool * sentinel head)\n\n".format(pool_head_ptr or 0))

        if not pool_head_ptr:
            out.write("ERROR: hfi_adapter_t.pool is NULL.\n")
            out.close()
            print_out_str("dump_hfi_adapter_pool: pool is NULL")
            return

        out.write(SEP + "\n\n")

        # ------------------------------------------------------------------ #
        # Step 3: Compute hfi_buffer_pool field offsets                       #
        # ------------------------------------------------------------------ #
        # struct hfi_buffer_pool { mutex lock; list_head node; atomic_t available; hfi_cmdbuf_t buffer_t; }
        bp_lock_off = self._hfi_get_offset('struct hfi_buffer_pool', 'lock', 0)
        bp_node_off = self._hfi_get_offset('struct hfi_buffer_pool', 'node', MUTEX_SIZE)
        bp_avail_off = self._hfi_get_offset('struct hfi_buffer_pool', 'available', MUTEX_SIZE + 2 * PTR)
        bp_buffer_t_off = self._hfi_get_offset('struct hfi_buffer_pool', 'buffer_t',
                                               MUTEX_SIZE + 2 * PTR + 4 + 4)

        # struct hfi_cmdbuf_t field offsets (relative to buffer_t start)
        # { mutex lock; enum cmd_type; u32 unique_id; u32 obj_id; u32 size;
        #   hfi_core_cmds_buf_desc buf; list_head node; list_head cmd_buf_chain;
        #   hfi_client_t* ctx; hfi_buffer_pool* pool;
        #   atomic_t buffer_send_done; bool is_released; atomic_t waiting_for_rsp;
        #   enum virtq_type; }
        cb_lock_off = self._hfi_get_offset('struct hfi_cmdbuf_t', 'lock', 0)
        cb_cmdtype_off = self._hfi_get_offset('struct hfi_cmdbuf_t', 'cmd_type', MUTEX_SIZE)
        cb_uid_off = self._hfi_get_offset('struct hfi_cmdbuf_t', 'unique_id', MUTEX_SIZE + 4)
        cb_objid_off = self._hfi_get_offset('struct hfi_cmdbuf_t', 'obj_id', MUTEX_SIZE + 8)
        cb_size_off = self._hfi_get_offset('struct hfi_cmdbuf_t', 'size', MUTEX_SIZE + 12)
        cb_buf_off = self._hfi_get_offset('struct hfi_cmdbuf_t', 'buf', MUTEX_SIZE + 16)
        cb_node_off = self._hfi_get_offset('struct hfi_cmdbuf_t', 'node', None)
        cb_chain_off = self._hfi_get_offset('struct hfi_cmdbuf_t', 'cmd_buf_chain', None)
        cb_ctx_off = self._hfi_get_offset('struct hfi_cmdbuf_t', 'ctx', None)
        cb_pool_off = self._hfi_get_offset('struct hfi_cmdbuf_t', 'pool', None)
        cb_sent_off = self._hfi_get_offset('struct hfi_cmdbuf_t', 'buffer_send_done', None)
        cb_released_off = self._hfi_get_offset('struct hfi_cmdbuf_t', 'is_released', None)
        cb_waitrsp_off = self._hfi_get_offset('struct hfi_cmdbuf_t', 'waiting_for_rsp', None)
        cb_virtq_off = self._hfi_get_offset('struct hfi_cmdbuf_t', 'virtq_type', None)

        # hfi_core_cmds_buf_desc offsets (relative to buf field start)
        # { void* pbuf_vaddr; u64 priv_dva; size_t size; enum prio_info; u32 priv_idx; u32 flag; }
        desc_vaddr_off = self._hfi_get_offset('struct hfi_core_cmds_buf_desc', 'pbuf_vaddr', 0)
        desc_dva_off = self._hfi_get_offset('struct hfi_core_cmds_buf_desc', 'priv_dva', PTR)
        desc_size_off = self._hfi_get_offset('struct hfi_core_cmds_buf_desc', 'size', PTR + 8)
        desc_prio_off = self._hfi_get_offset('struct hfi_core_cmds_buf_desc', 'prio_info', PTR + 8 + PTR)
        desc_idx_off = self._hfi_get_offset('struct hfi_core_cmds_buf_desc', 'priv_idx', PTR + 8 + PTR + 4)
        desc_flag_off = self._hfi_get_offset('struct hfi_core_cmds_buf_desc', 'flag', PTR + 8 + PTR + 8)

        # If cb_node_off not available from DWARF, compute manually
        if cb_node_off is None:
            # buf ends at: MUTEX_SIZE+16 + sizeof(hfi_core_cmds_buf_desc)
            desc_size = self.ramdump.sizeof('struct hfi_core_cmds_buf_desc') or (PTR + 8 + PTR + 4 + 4 + 4 + 4)
            cb_node_off = MUTEX_SIZE + 16 + desc_size
            cb_chain_off = cb_node_off + 2 * PTR
            cb_ctx_off = cb_chain_off + 2 * PTR
            cb_pool_off = cb_ctx_off + PTR
            cb_sent_off = cb_pool_off + PTR
            cb_released_off = cb_sent_off + 4
            cb_waitrsp_off = cb_released_off + 4
            cb_virtq_off = cb_waitrsp_off + 4

        out.write("Struct offsets used:\n")
        out.write("  hfi_buffer_pool: lock={} node={} available={} buffer_t={}\n".format(
            bp_lock_off, bp_node_off, bp_avail_off, bp_buffer_t_off))
        out.write("  hfi_cmdbuf_t: lock={} cmd_type={} unique_id={} obj_id={} size={} "
                  "buf={} node={} chain={} ctx={} pool={} sent={} released={} "
                  "waitrsp={} virtq={}\n".format(
                      cb_lock_off, cb_cmdtype_off, cb_uid_off, cb_objid_off, cb_size_off,
                      cb_buf_off, cb_node_off, cb_chain_off, cb_ctx_off, cb_pool_off,
                      cb_sent_off, cb_released_off, cb_waitrsp_off, cb_virtq_off))
        out.write("  hfi_core_cmds_buf_desc: vaddr={} dva={} size={} prio={} "
                  "idx={} flag={}\n\n".format(
                      desc_vaddr_off, desc_dva_off, desc_size_off,
                      desc_prio_off, desc_idx_off, desc_flag_off))
        out.write(SEP + "\n\n")

        # ------------------------------------------------------------------ #
        # Step 4: Walk pool->node list                                        #
        # ------------------------------------------------------------------ #
        # pool_head_ptr is the sentinel node; its .node list_head links to
        # the real pool nodes.  The list_head is at bp_node_off within each node.
        sentinel_node_addr = pool_head_ptr + bp_node_off
        sentinel_next = self.ramdump.read_pointer(sentinel_node_addr)

        if not sentinel_next or sentinel_next == sentinel_node_addr:
            out.write("pool->node list is EMPTY — no pool nodes allocated.\n")
            out.close()
            print_out_str("dump_hfi_adapter_pool: pool list is empty")
            return

        # Walk the list
        pool_nodes = []
        current = sentinel_next
        visited = set()
        while current and current != sentinel_node_addr and len(pool_nodes) < MAX_POOL_SIZE + 4:
            if current in visited:
                out.write("WARNING: cycle detected in pool->node list at 0x{:x}\n".format(current))
                break
            visited.add(current)
            node_addr = current - bp_node_off   # container_of(current, hfi_buffer_pool, node)
            pool_nodes.append(node_addr)
            current = self.ramdump.read_pointer(current)   # list_head.next

        total = len(pool_nodes)
        avail_count = 0
        in_use_count = 0
        waiting_count = 0

        out.write("pool sentinel head @ 0x{:x}\n".format(pool_head_ptr))
        out.write("pool->node list: {} node(s) found (MAX_POOL_SIZE={})\n\n".format(
            total, MAX_POOL_SIZE))
        out.write(SEP + "\n\n")

        for idx, node_addr in enumerate(pool_nodes):
            try:
                available = self.ramdump.read_u32(node_addr + bp_avail_off)
                node_next = self.ramdump.read_pointer(node_addr + bp_node_off)
                node_prev = self.ramdump.read_pointer(node_addr + bp_node_off + PTR)
            except Exception as ex:
                out.write("[pool_node {:2d}] ERROR reading hfi_buffer_pool @ "
                          "0x{:x}: {}\n\n".format(idx, node_addr, ex))
                continue

            avail_str = "FREE (available=1)" if available else "IN-USE (available=0)"
            if available:
                avail_count += 1
            else:
                in_use_count += 1

            out.write("{}\n".format(SEP2))
            out.write("[pool_node {:2d}]  (struct hfi_buffer_pool *) @ 0x{:x}  {}\n".format(
                idx, node_addr, avail_str))
            out.write("  .lock           @ 0x{:x}\n".format(node_addr + bp_lock_off))
            out.write("  .node.next      = 0x{:x}\n".format(node_next or 0))
            out.write("  .node.prev      = 0x{:x}\n".format(node_prev or 0))
            out.write("  .available      = {}  ({})\n".format(available, avail_str))

            # Read hfi_cmdbuf_t fields
            bt_base = node_addr + bp_buffer_t_off
            out.write("  .buffer_t  (struct hfi_cmdbuf_t *) @ 0x{:x}\n".format(bt_base))

            try:
                cmd_type = self.ramdump.read_u32(bt_base + cb_cmdtype_off)
                unique_id = self.ramdump.read_u32(bt_base + cb_uid_off)
                obj_id = self.ramdump.read_u32(bt_base + cb_objid_off)
                buf_size = self.ramdump.read_u32(bt_base + cb_size_off)

                # hfi_core_cmds_buf_desc
                buf_base = bt_base + cb_buf_off
                pbuf_vaddr = self.ramdump.read_pointer(buf_base + desc_vaddr_off)
                priv_dva = self.ramdump.read_u64(buf_base + desc_dva_off)
                desc_sz = self.ramdump.read_u64(buf_base + desc_size_off)
                prio_info = self.ramdump.read_u32(buf_base + desc_prio_off)
                priv_idx = self.ramdump.read_u32(buf_base + desc_idx_off)
                flag = self.ramdump.read_u32(buf_base + desc_flag_off)

                # Remaining cmdbuf fields
                ctx_ptr = self.ramdump.read_pointer(bt_base + cb_ctx_off)
                pool_ptr = self.ramdump.read_pointer(bt_base + cb_pool_off)
                sent = self.ramdump.read_u32(bt_base + cb_sent_off)
                released = self.ramdump.read_u32(bt_base + cb_released_off)
                waitrsp = self.ramdump.read_u32(bt_base + cb_waitrsp_off)
                virtq_type = self.ramdump.read_u32(bt_base + cb_virtq_off)

            except Exception as ex:
                out.write("    ERROR reading hfi_cmdbuf_t fields: {}\n\n".format(ex))
                continue

            cmd_type_name = CMDBUF_TYPE_NAMES.get(cmd_type, '0x{:x}'.format(cmd_type))
            prio_name = PRIO_NAMES.get(prio_info, '0x{:x}'.format(prio_info))
            virtq_name = VIRTQ_TYPE_NAMES.get(virtq_type, '0x{:x}'.format(virtq_type))

            out.write("    .lock              @ 0x{:x}\n".format(bt_base + cb_lock_off))
            out.write("    .cmd_type          = {}  ({})\n".format(cmd_type, cmd_type_name))
            out.write("    .unique_id         = 0x{:08x}  "
                      "(client_id={})\n".format(unique_id, unique_id & 0xFF))
            out.write("    .obj_id            = 0x{:08x}\n".format(obj_id))
            out.write("    .size              = {}\n".format(buf_size))
            out.write("    .buf  (struct hfi_core_cmds_buf_desc *) @ 0x{:x}\n".format(buf_base))
            out.write("      .pbuf_vaddr      = 0x{:x}  (-> 4KB HFI page)\n".format(
                pbuf_vaddr or 0))
            out.write("      .priv_dva        = 0x{:016x}  (device VA)\n".format(priv_dva or 0))
            out.write("      .size            = {}\n".format(desc_sz or 0))
            out.write("      .prio_info       = {}  ({})\n".format(prio_info, prio_name))
            out.write("      .priv_idx        = {}\n".format(priv_idx or 0))
            out.write("      .flag            = 0x{:x}\n".format(flag or 0))
            out.write("    .ctx               = 0x{:x}  (struct hfi_client_t *)\n".format(
                ctx_ptr or 0))
            out.write("    .pool              = 0x{:x}  (back-ptr to this pool node)\n".format(
                pool_ptr or 0))
            out.write("    .buffer_send_done  = {}\n".format(sent or 0))
            out.write("    .is_released       = {}\n".format(bool(released)))
            out.write("    .waiting_for_rsp   = {}  {}\n".format(
                waitrsp or 0,
                "<-- WAITING FOR DCP RESPONSE" if waitrsp else ""))
            out.write("    .virtq_type        = {}  ({})\n".format(virtq_type, virtq_name))

            if waitrsp:
                waiting_count += 1

            # ---------------------------------------------------------------- #
            # Decode the HFI packets inside pbuf_vaddr                         #
            # ---------------------------------------------------------------- #
            if not pbuf_vaddr or not desc_sz:
                out.write("\n    [HFI page] pbuf_vaddr=0 or size=0 -- skipped\n\n")
                continue

            read_len = min(int(desc_sz), HFI_PAGE_SIZE)
            try:
                raw = bytes(self.ramdump.get_bin_data(pbuf_vaddr, read_len))
                if len(raw) != read_len:
                    raise ValueError("short HFI page read: {} of {} bytes".format(
                        len(raw), read_len))
            except Exception as ex:
                out.write("    [HFI page] bulk read failed; using virtual "
                          "fallback: {}\n".format(ex))
                raw = bytearray()
                for off in range(0, read_len, 4):
                    val = self.ramdump.read_u32(pbuf_vaddr + off)
                    raw += _struct.pack('<I', val if val is not None else 0)
                raw = bytes(raw)

            if len(raw) < HFI_HDR_SIZE:
                out.write("\n    [HFI page] too short ({} bytes)\n\n".format(len(raw)))
                continue

            (cmd_buff_info, dev_obj_id, ts_hi, ts_lo,
             header_id, rsv0, rsv1, num_packets) = _struct.unpack_from('<IIIIIIII', raw, 0)

            total_sz = cmd_buff_info & 0x00FFFFFF
            buff_type = (cmd_buff_info >> 24) & 0xFF
            device_id = dev_obj_id & 0xFFFF
            object_id = (dev_obj_id >> 16) & 0xFFFF
            display_id = object_id & 0xFF
            cb_flags = (object_id >> 8) & 0xFF
            full_ts = (ts_hi << 32) | ts_lo

            cb_flag_strs = []
            if cb_flags & 0x01: cb_flag_strs.append("ASYNC")
            if cb_flags & 0x02: cb_flag_strs.append("NO_WAIT")
            if cb_flags & 0x04: cb_flag_strs.append("CHAINED")
            cb_flag_str = "|".join(cb_flag_strs) if cb_flag_strs else "NONE"
            buff_type_name = self.HFI_CMD_BUFF_TYPE_NAMES.get(
                buff_type, '0x{:02x}'.format(buff_type))

            out.write("\n    {}\n".format(SEP3))
            out.write("    [HFI page @ 0x{:x}]  read_len={}\n".format(pbuf_vaddr, read_len))

            if total_sz == 0 and num_packets == 0:
                out.write("    hfi_header: EMPTY (all-zero) -- buffer not yet filled\n\n")
                continue

            out.write("    hfi_header  (struct hfi_header *) @ 0x{:x}\n".format(pbuf_vaddr))
            out.write("      [w0] cmd_buff_info = 0x{:08x}  "
                      "total_size={}  buff_type={} ({})\n".format(
                          cmd_buff_info, total_sz, buff_type, buff_type_name))
            out.write("      [w1] dev_obj_id    = 0x{:08x}  "
                      "device_id={}  object_id=0x{:04x}  "
                      "display_id={}  cb_flags=0x{:02x} ({})\n".format(
                          dev_obj_id, device_id, object_id, display_id, cb_flags, cb_flag_str))
            out.write("      [w2] timestamp_hi  = 0x{:08x}\n".format(ts_hi))
            out.write("      [w3] timestamp_lo  = 0x{:08x}  full_ts=0x{:016x}\n".format(
                ts_lo, full_ts))
            out.write("      [w4] header_id     = 0x{:08x}\n".format(header_id))
            out.write("      [w5] reserved[0]   = 0x{:08x}\n".format(rsv0))
            out.write("      [w6] reserved[1]   = 0x{:08x}\n".format(rsv1))
            out.write("      [w7] num_packets   = {}\n".format(num_packets))

            if total_sz < HFI_HDR_SIZE or num_packets == 0:
                out.write("    (no packets)\n\n")
                continue

            effective_sz = min(total_sz, read_len)
            pkt_off = HFI_HDR_SIZE

            for pkt_num in range(num_packets):
                if pkt_off + HFI_PKT_HDR_SIZE > effective_sz:
                    out.write("    [pkt {:2d}] truncated at offset {}\n".format(
                        pkt_num, pkt_off))
                    break

                (payload_info, cmd, flags, pkt_id_field,
                 packet_id, p0, p1, p2) = _struct.unpack_from('<IIIIIIII', raw, pkt_off)

                pkt_size = payload_info & 0x001FFFFF
                payload_type = (payload_info >> 21) & 0x7FF
                layer_id = pkt_id_field & 0xFFFF

                if pkt_size < HFI_PKT_HDR_SIZE:
                    out.write("    [pkt {:2d}] invalid pkt_size={}\n".format(
                        pkt_num, pkt_size))
                    break

                payload_size = pkt_size - HFI_PKT_HDR_SIZE
                payload_off = pkt_off + HFI_PKT_HDR_SIZE

                cmd_name = self._hfi_cmd_name(cmd)
                flags_str = self._hfi_flags_str(flags)
                pt_name = self.HFI_PAYLOAD_TYPE_NAMES.get(
                    payload_type, '0x{:x}'.format(payload_type))

                pkt_va = pbuf_vaddr + pkt_off
                payload_va = pbuf_vaddr + payload_off

                out.write("\n    [pkt {:2d}]  (struct hfi_packet *) @ 0x{:x}\n".format(
                    pkt_num, pkt_va))
                out.write("      [w0] payload_info = 0x{:08x}  "
                          "pkt_size={}  payload_type={} ({})\n".format(
                              payload_info, pkt_size, payload_type, pt_name))
                out.write("      [w1] cmd          = 0x{:08x}  ({})\n".format(cmd, cmd_name))
                out.write("      [w2] flags        = 0x{:08x}  ({})\n".format(flags, flags_str))
                out.write("      [w3] id           = 0x{:08x}  "
                          "display/layer_id=0x{:04x}\n".format(pkt_id_field, layer_id))
                out.write("      [w4] packet_id    = 0x{:08x}\n".format(packet_id))
                out.write("      [w5] reserved[0]  = 0x{:08x}\n".format(p0))
                out.write("      [w6] reserved[1]  = 0x{:08x}\n".format(p1))
                out.write("      [w7] reserved[2]  = 0x{:08x}\n".format(p2))
                out.write("           payload_va=0x{:x}  payload_size={}\n".format(
                    payload_va, payload_size))

                # Decode SET_PROPERTY KV pairs
                if cmd == 0x02000001 and payload_type == 0x2 and payload_size >= 4:
                    kv_props = self._hfi_decode_kv_payload(raw, payload_off, payload_size)
                    if kv_props:
                        out.write("      KV properties ({}):\n".format(len(kv_props)))
                        for prop_name, ver, dsize, vals in kv_props:
                            val_str = ' '.join('0x{:08x}'.format(v) for v in vals)
                            out.write("        key={:<55s}  ver={}  dsize={}  "
                                      "value=[{}]\n".format(prop_name, ver, dsize, val_str))
                # Decode FRAME_TRIGGER
                elif cmd == 0x02000003 and payload_size >= 4:
                    flag_str = self._hfi_decode_frame_trigger_payload(
                        raw, payload_off, payload_size)
                    out.write("      commit_flag={}\n".format(flag_str))
                # Raw hex for other payloads
                elif payload_size > 0:
                    dump_len = min(payload_size, 64)
                    hex_str = ' '.join('{:02x}'.format(b)
                                       for b in bytearray(raw[payload_off:payload_off + dump_len]))
                    suffix = '...' if payload_size > 64 else ''
                    out.write("      raw[0:{}]: {}{}\n".format(dump_len, hex_str, suffix))

                pkt_off += pkt_size

            out.write("\n")

        # ------------------------------------------------------------------ #
        # Summary                                                             #
        # ------------------------------------------------------------------ #
        out.write(SEP + "\n")
        out.write("SUMMARY\n")
        out.write("  Total pool nodes   : {}\n".format(total))
        out.write("  Available (free)   : {}\n".format(avail_count))
        out.write("  In-use             : {}\n".format(in_use_count))
        out.write("  Waiting for DCP rsp: {}\n".format(waiting_count))
        if avail_count == 0:
            out.write("\n  *** POOL EXHAUSTED: all {} buffers are in-use. ***\n".format(total))
            out.write("  get_avail_buffer() will fail with 'could not get buffer'.\n")
            if waiting_count > 0:
                out.write("  {} buffer(s) are waiting for a DCP response "
                          "(waiting_for_rsp=1).\n".format(waiting_count))
                out.write("  If DCP never responds, these buffers will never be "
                          "returned to the pool.\n")
        out.write(SEP + "\n")

        out.close()
        print_out_str("dump_hfi_adapter_pool: wrote display_info/dcp_hfi_adapter_pool_dump.txt")

    def dump_hfi_kms_listeners(self):
        """
        Dump the hfi_kms client's packet_listeners list to
        display_info/dcp_hfi_kms_listeners.txt.

        This shows every pending listener registered with the HFI adapter
        at crash time, which reveals where hfi_adapter_unpack_cmd_buf is
        blocked waiting for a response — each listener_list entry
        represents one outstanding TX packet waiting for its RX response.

        Chain:
          sde_dbg_base.dev -> driver_data -> drm_device
            -> dev_private  -> msm_drm_private
            -> kms          -> msm_kms * -> sde_kms * (container_of)
            -> hfi_kms      -> struct hfi_kms *
            -> hfi_client   -> struct hfi_client_t  (embedded)
               .packet_listeners.list_ptr  (list_head head)
                 -> listener_list entries:
                      packet_id, cmd_id, event_id, obj_id,
                      listener_obj *, remove_on_cb, mark_for_deletion
        """
        SEP = '=' * 100
        SEP2 = '-' * 80

        print_out_str("Starting dump_hfi_kms_listeners")

        try:
            out = self.ramdump.open_file('display_info/dcp_hfi_kms_listeners.txt', 'w')
        except Exception as ex:
            print_out_str("dump_hfi_kms_listeners: cannot open output: {}".format(ex))
            return

        def _foff(sname, fname, fallback=None):
            v = self.ramdump.field_offset(sname, fname)
            return fallback if v is None else v

        PTR = self.ramdump.sizeof('void *') or 8

        try:
            out.write("{}\n".format(SEP))
            out.write("HFI KMS CLIENT PACKET LISTENERS DUMP\n")
            out.write("Purpose: shows pending listeners in hfi_client_t.packet_listeners\n")
            out.write("         each entry = one TX packet awaiting its RX response\n")
            out.write("         use this to identify where hfi_adapter_unpack_cmd_buf\n")
            out.write("         is stalled waiting for firmware response\n")
            out.write("{}\n\n".format(SEP))

            # ------------------------------------------------------------------
            # 1. sde_dbg_base -> device -> driver_data -> drm_device
            # ------------------------------------------------------------------
            sde_dbg_base_sym = self.ramdump.address_of('sde_dbg_base')
            if not sde_dbg_base_sym:
                out.write("ERROR: symbol 'sde_dbg_base' not found\n")
                return
            out.write("(struct sde_dbg_base)      @ 0x{:x}  [global symbol]\n".format(
                sde_dbg_base_sym))

            dbg_dev_off = _foff('struct sde_dbg_base', 'dev')
            if dbg_dev_off is None:
                out.write("ERROR: cannot resolve sde_dbg_base.dev offset\n")
                return
            pdev_dev_ptr = self.ramdump.read_pointer(sde_dbg_base_sym + dbg_dev_off)
            if not pdev_dev_ptr:
                out.write("ERROR: sde_dbg_base.dev is NULL\n")
                return
            out.write("  .dev ptr               @ 0x{:x}  "
                      "[sde_dbg_base+0x{:x}] -> 0x{:x}\n".format(
                          sde_dbg_base_sym + dbg_dev_off, dbg_dev_off, pdev_dev_ptr))
            out.write("(struct device *)          @ 0x{:x}  [pdev->dev]\n".format(
                pdev_dev_ptr))

            drv_data_off = _foff('struct device', 'driver_data')
            if drv_data_off is None:
                out.write("ERROR: cannot resolve device.driver_data offset\n")
                return
            drm_dev_ptr = self.ramdump.read_pointer(pdev_dev_ptr + drv_data_off)
            if not drm_dev_ptr:
                out.write("ERROR: device->driver_data (drm_device) is NULL\n")
                return
            out.write("  .driver_data ptr       @ 0x{:x}  "
                      "[device+0x{:x}] -> 0x{:x}\n".format(
                          pdev_dev_ptr + drv_data_off, drv_data_off, drm_dev_ptr))
            out.write("(struct drm_device *)      @ 0x{:x}\n".format(drm_dev_ptr))

            # ------------------------------------------------------------------
            # 2. drm_device -> dev_private -> msm_drm_private -> kms -> sde_kms
            # ------------------------------------------------------------------
            dev_private_off = _foff('struct drm_device', 'dev_private')
            if dev_private_off is None:
                out.write("ERROR: cannot resolve drm_device.dev_private offset\n")
                return
            msm_priv_ptr = self.ramdump.read_pointer(drm_dev_ptr + dev_private_off)
            if not msm_priv_ptr:
                out.write("ERROR: drm_device->dev_private is NULL\n")
                return
            out.write("  .dev_private ptr       @ 0x{:x}  "
                      "[drm_device+0x{:x}] -> 0x{:x}\n".format(
                          drm_dev_ptr + dev_private_off, dev_private_off, msm_priv_ptr))
            out.write("(struct msm_drm_private *) @ 0x{:x}\n".format(msm_priv_ptr))

            kms_off = _foff('struct msm_drm_private', 'kms')
            if kms_off is None:
                out.write("ERROR: cannot resolve msm_drm_private.kms offset\n")
                return
            msm_kms_ptr = self.ramdump.read_pointer(msm_priv_ptr + kms_off)
            if not msm_kms_ptr:
                out.write("ERROR: msm_drm_private->kms is NULL\n")
                return
            out.write("  .kms ptr               @ 0x{:x}  "
                      "[msm_drm_private+0x{:x}] -> 0x{:x}\n".format(
                          msm_priv_ptr + kms_off, kms_off, msm_kms_ptr))
            out.write("(struct msm_kms *)         @ 0x{:x}\n".format(msm_kms_ptr))

            sde_kms_base_off = _foff('struct sde_kms', 'base') or 0
            sde_kms_ptr = msm_kms_ptr - sde_kms_base_off
            out.write("(struct sde_kms *)         @ 0x{:x}  "
                      "[container_of msm_kms, base_off=0x{:x}]\n".format(
                          sde_kms_ptr, sde_kms_base_off))

            # ------------------------------------------------------------------
            # 3. sde_kms -> hfi_kms
            # ------------------------------------------------------------------
            hfi_kms_ptr_off = _foff('struct sde_kms', 'hfi_kms')
            if hfi_kms_ptr_off is None:
                out.write("ERROR: cannot resolve sde_kms.hfi_kms offset\n")
                return
            hfi_kms_ptr = self.ramdump.read_pointer(sde_kms_ptr + hfi_kms_ptr_off)
            if not hfi_kms_ptr:
                out.write("ERROR: sde_kms->hfi_kms is NULL\n")
                return
            out.write("  .hfi_kms ptr           @ 0x{:x}  "
                      "[sde_kms+0x{:x}] -> 0x{:x}\n".format(
                          sde_kms_ptr + hfi_kms_ptr_off, hfi_kms_ptr_off, hfi_kms_ptr))
            out.write("(struct hfi_kms *)         @ 0x{:x}\n".format(hfi_kms_ptr))

            # ------------------------------------------------------------------
            # 4. hfi_kms -> hfi_client (embedded struct, not a pointer)
            # ------------------------------------------------------------------
            hfi_client_off = _foff('struct hfi_kms', 'hfi_client')
            if hfi_client_off is None:
                out.write("ERROR: cannot resolve hfi_kms.hfi_client offset\n")
                return
            hfi_client_addr = hfi_kms_ptr + hfi_client_off
            out.write("  .hfi_client            @ 0x{:x}  "
                      "[hfi_kms+0x{:x}]  (embedded, not a pointer)\n".format(
                          hfi_client_addr, hfi_client_off))
            out.write("(struct hfi_client_t)      @ 0x{:x}\n".format(hfi_client_addr))

            # client_id
            client_id_off = _foff('struct hfi_client_t', 'client_id')
            client_id = (self.ramdump.read_u32(hfi_client_addr + client_id_off)
                         if client_id_off is not None else None)
            out.write("  .client_id             @ 0x{:x}  = {}\n".format(
                hfi_client_addr + (client_id_off or 0), client_id))

            # host pointer (hfi_adapter_t *)
            host_off = _foff('struct hfi_client_t', 'host')
            host_ptr = (self.ramdump.read_pointer(hfi_client_addr + host_off)
                        if host_off is not None else None)
            out.write("  .host ptr              @ 0x{:x}  "
                      "[hfi_client+0x{:x}] -> {}\n".format(
                          hfi_client_addr + (host_off or 0), host_off or 0,
                          "0x{:x}".format(host_ptr) if host_ptr else "NULL"))

            # process_cmd_buf / process_event function pointers
            pcb_off = _foff('struct hfi_client_t', 'process_cmd_buf')
            pev_off = _foff('struct hfi_client_t', 'process_event')
            pcb_ptr = (self.ramdump.read_pointer(hfi_client_addr + pcb_off)
                       if pcb_off is not None else None)
            pev_ptr = (self.ramdump.read_pointer(hfi_client_addr + pev_off)
                       if pev_off is not None else None)
            out.write("  .process_cmd_buf ptr   @ 0x{:x}  "
                      "[hfi_client+0x{:x}] -> {}\n".format(
                          hfi_client_addr + (pcb_off or 0), pcb_off or 0,
                          "0x{:x}".format(pcb_ptr) if pcb_ptr else "NULL"))
            out.write("  .process_event ptr     @ 0x{:x}  "
                      "[hfi_client+0x{:x}] -> {}\n".format(
                          hfi_client_addr + (pev_off or 0), pev_off or 0,
                          "0x{:x}".format(pev_ptr) if pev_ptr else "NULL"))

            # priv pointer (points back to hfi_kms)
            priv_off = _foff('struct hfi_client_t', 'priv')
            priv_ptr = (self.ramdump.read_pointer(hfi_client_addr + priv_off)
                        if priv_off is not None else None)
            out.write("  .priv ptr              @ 0x{:x}  "
                      "[hfi_client+0x{:x}] -> {}  (-> hfi_kms)\n".format(
                          hfi_client_addr + (priv_off or 0), priv_off or 0,
                          "0x{:x}".format(priv_ptr) if priv_ptr else "NULL"))

            # ------------------------------------------------------------------
            # 5. Walk hfi_client.packet_listeners.list_ptr
            #    struct listener_list { list_head list_ptr; u32 packet_id;
            #                          u32 cmd_id; u32 event_id; u32 obj_id;
            #                          void *listener_obj; bool remove_on_cb;
            #                          bool mark_for_deletion; }
            # ------------------------------------------------------------------
            pl_off = _foff('struct hfi_client_t', 'packet_listeners')
            # pl_off may be None if DWARF lacks listener_list — handled below

            # packet_listeners is a listener_list struct; its first field is
            # list_ptr (a list_head), which is the list head.
            #
            # struct listener_list is not always present in DWARF symbols
            # (it is a module-internal struct in hfi_adapter.c/.h).
            # Fall back to manually computed offsets derived from the known
            # hfi_client_t layout (verified from live output):
            #
            #   hfi_client_t layout (arm64, 64-bit pointers):
            #     +0x00  node          (list_head, 16)
            #     +0x10  lock          (mutex,     40 w/ padding)
            #     +0x38  cmd_buf_list  (list_head, 16)
            #     +0x48  listener_lock (mutex,     40 w/ padding)
            #     +0x70  packet_listeners (listener_list, 48)
            #     +0xa0  process_cmd_buf  (fn ptr)
            #
            #   listener_list layout (arm64):
            #     +0x00  list_ptr      (list_head: next+prev, 16)
            #     +0x10  packet_id     (u32)
            #     +0x14  cmd_id        (u32)
            #     +0x18  event_id      (u32)
            #     +0x1c  obj_id        (u32)
            #     +0x20  listener_obj  (ptr, 8)
            #     +0x28  remove_on_cb  (bool, 1)
            #     +0x29  mark_for_deletion (bool, 1)
            #     total: 0x30 = 48 bytes
            LL_LIST_PTR_OFF = 0x00   # list_ptr within listener_list
            LL_PACKET_ID_OFF = 0x10
            LL_CMD_ID_OFF = 0x14
            LL_EVENT_ID_OFF = 0x18
            LL_OBJ_ID_OFF = 0x1c
            LL_LOBJ_OFF = 0x20
            LL_ROC_OFF = 0x28
            LL_MFD_OFF = 0x29
            LL_SIZE = 0x30

            # hfi_client_t.packet_listeners offset: try DWARF first, fall back
            # to +0x70 derived from process_cmd_buf being at +0xa0
            if pl_off is None:
                # Derive from process_cmd_buf offset: packet_listeners ends
                # at process_cmd_buf, size = LL_SIZE = 0x30
                if pcb_off is not None:
                    pl_off = pcb_off - LL_SIZE
                else:
                    pl_off = 0x70   # hardcoded fallback
                out.write("  NOTE: packet_listeners offset from DWARF unavailable, "
                          "using computed 0x{:x}\n".format(pl_off))

            lp_off_in_ll = self.ramdump.field_offset('struct listener_list', 'list_ptr')
            if lp_off_in_ll is None:
                lp_off_in_ll = LL_LIST_PTR_OFF
                out.write("  NOTE: listener_list.list_ptr offset from DWARF unavailable, "
                          "using hardcoded 0x{:x}\n".format(lp_off_in_ll))

            # Override all listener_list field offsets with hardcoded values
            # when DWARF is unavailable (use DWARF if present, else hardcoded)
            def _ll_off(fname, hardcoded):
                v = self.ramdump.field_offset('struct listener_list', fname)
                return v if v is not None else hardcoded

            ll_pktid_off = _ll_off('packet_id', LL_PACKET_ID_OFF)
            ll_cmdid_off = _ll_off('cmd_id', LL_CMD_ID_OFF)
            ll_evtid_off = _ll_off('event_id', LL_EVENT_ID_OFF)
            ll_objid_off = _ll_off('obj_id', LL_OBJ_ID_OFF)
            ll_lobj_off = _ll_off('listener_obj', LL_LOBJ_OFF)
            ll_roc_off = _ll_off('remove_on_cb', LL_ROC_OFF)
            ll_mfd_off = _ll_off('mark_for_deletion', LL_MFD_OFF)

            list_head_addr = hfi_client_addr + pl_off + lp_off_in_ll
            # Read next/prev of the list head to show if list is empty
            lh_next_off = self.ramdump.field_offset('struct list_head', 'next') or 0
            lh_prev_off = self.ramdump.field_offset('struct list_head', 'prev') or PTR
            lh_next = self.ramdump.read_pointer(list_head_addr + lh_next_off)
            lh_prev = self.ramdump.read_pointer(list_head_addr + lh_prev_off)
            out.write("  .packet_listeners      @ 0x{:x}  "
                      "[hfi_client+0x{:x}]\n".format(
                          hfi_client_addr + pl_off, pl_off))
            out.write("  .list_ptr (head)       @ 0x{:x}  "
                      "[packet_listeners+0x{:x}]\n".format(
                          list_head_addr, lp_off_in_ll))
            out.write("    .next                @ 0x{:x}  -> {}\n".format(
                list_head_addr + lh_next_off,
                "0x{:x}".format(lh_next) if lh_next else "NULL"))
            out.write("    .prev                @ 0x{:x}  -> {}\n".format(
                list_head_addr + lh_prev_off,
                "0x{:x}".format(lh_prev) if lh_prev else "NULL"))
            out.write("    list_empty           : {}\n\n".format(
                lh_next == list_head_addr))

            # listener_list field offsets already computed above with hardcoded fallbacks

            out.write("{}\n".format(SEP))
            out.write("PENDING LISTENERS (packet_listeners list)\n")
            out.write("{}\n\n".format(SEP))

            count = 0
            for ll_addr in ListWalker(self.ramdump, list_head_addr, lp_off_in_ll):
                pkt_id = (self.ramdump.read_u32(ll_addr + ll_pktid_off)
                          if ll_pktid_off is not None else None)
                cmd_id = (self.ramdump.read_u32(ll_addr + ll_cmdid_off)
                          if ll_cmdid_off is not None else None)
                evt_id = (self.ramdump.read_u32(ll_addr + ll_evtid_off)
                          if ll_evtid_off is not None else None)
                obj_id = (self.ramdump.read_u32(ll_addr + ll_objid_off)
                          if ll_objid_off is not None else None)
                lobj = (self.ramdump.read_pointer(ll_addr + ll_lobj_off)
                        if ll_lobj_off is not None else None)
                roc = (self.ramdump.read_byte(ll_addr + ll_roc_off)
                       if ll_roc_off is not None else None)
                mfd = (self.ramdump.read_byte(ll_addr + ll_mfd_off)
                       if ll_mfd_off is not None else None)

                # Decode cmd_id name using existing HFI command name helper
                cmd_name = self._hfi_cmd_name(cmd_id) if cmd_id is not None else 'N/A'

                # list_ptr next/prev inside this listener_list entry
                ll_lh_next = self.ramdump.read_pointer(
                    ll_addr + lp_off_in_ll + lh_next_off)
                ll_lh_prev = self.ramdump.read_pointer(
                    ll_addr + lp_off_in_ll + lh_prev_off)

                out.write("  [listener {:3d}] (struct listener_list *) @ 0x{:x}\n".format(
                    count, ll_addr))
                out.write("    .list_ptr          @ 0x{:x}\n".format(
                    ll_addr + lp_off_in_ll))
                out.write("      .next            @ 0x{:x}  -> {}\n".format(
                    ll_addr + lp_off_in_ll + lh_next_off,
                    "0x{:x}".format(ll_lh_next) if ll_lh_next else "NULL"))
                out.write("      .prev            @ 0x{:x}  -> {}\n".format(
                    ll_addr + lp_off_in_ll + lh_prev_off,
                    "0x{:x}".format(ll_lh_prev) if ll_lh_prev else "NULL"))
                out.write("    .packet_id         @ 0x{:x}  = 0x{:08x}\n".format(
                    ll_addr + (ll_pktid_off or 0),
                    pkt_id if pkt_id is not None else 0))
                out.write("    .cmd_id            @ 0x{:x}  = 0x{:08x}  ({})\n".format(
                    ll_addr + (ll_cmdid_off or 0),
                    cmd_id if cmd_id is not None else 0, cmd_name))
                out.write("    .event_id          @ 0x{:x}  = 0x{:08x}\n".format(
                    ll_addr + (ll_evtid_off or 0),
                    evt_id if evt_id is not None else 0))
                out.write("    .obj_id            @ 0x{:x}  = 0x{:08x}\n".format(
                    ll_addr + (ll_objid_off or 0),
                    obj_id if obj_id is not None else 0))
                out.write("    .listener_obj ptr  @ 0x{:x}  -> {}\n".format(
                    ll_addr + (ll_lobj_off or 0),
                    "0x{:x}".format(lobj) if lobj else "NULL"))
                out.write("    .remove_on_cb      @ 0x{:x}  = {}\n".format(
                    ll_addr + (ll_roc_off or 0),
                    bool(roc) if roc is not None else 'N/A'))
                out.write("    .mark_for_deletion @ 0x{:x}  = {}\n".format(
                    ll_addr + (ll_mfd_off or 0),
                    bool(mfd) if mfd is not None else 'N/A'))

                # Resolve listener_obj as hfi_prop_listener:
                # hfi_prop_listener.hfi_prop_handler is the first field (fn ptr)
                if lobj:
                    handler_ptr = self.ramdump.read_pointer(lobj)
                    out.write("    (struct hfi_prop_listener *) @ 0x{:x}\n".format(lobj))
                    out.write("      .hfi_prop_handler @ 0x{:x}  -> {}\n".format(
                        lobj,
                        "0x{:x}".format(handler_ptr) if handler_ptr else "NULL"))

                out.write("\n")
                count += 1

            if count == 0:
                out.write("  (no pending listeners — list is empty)\n\n")
            else:
                out.write("{}\n".format(SEP2))
                out.write("Total pending listeners: {}\n".format(count))
                out.write("{}\n".format(SEP2))

            # ------------------------------------------------------------------
            # 6. Also dump hfi_kms embedded prop listeners for cross-reference
            # ------------------------------------------------------------------
            out.write("\n{}\n".format(SEP))
            out.write("HFI_KMS EMBEDDED PROP LISTENERS (for cross-reference)\n")
            out.write("{}\n\n".format(SEP))

            for fname, label in [
                ('device_init_listener', 'device_init_listener'),
                ('resource_vote_listener', 'resource_vote_listener'),
                ('trace_cfg_listener', 'trace_cfg_listener'),
                ('debug_set_prop_listener', 'debug_set_prop_listener'),
            ]:
                foff = _foff('struct hfi_kms', fname)
                if foff is None:
                    out.write("  {:<30}: offset unavailable\n".format(label))
                    continue
                listener_addr = hfi_kms_ptr + foff
                # hfi_prop_listener.hfi_prop_handler is the first field (fn ptr)
                handler_ptr = self.ramdump.read_pointer(listener_addr)
                out.write("  {:<30}: (struct hfi_prop_listener *) @ 0x{:x}  "
                          "[hfi_kms+0x{:x}]\n".format(label, listener_addr, foff))
                out.write("    .hfi_prop_handler ptr @ 0x{:x}  -> {}\n".format(
                    listener_addr,
                    "0x{:x}".format(handler_ptr) if handler_ptr else "NULL"))

            out.write("\n{}\n".format(SEP))
            out.write("END OF HFI KMS LISTENERS DUMP\n")
            out.write("{}\n".format(SEP))

        except Exception as ex:
            out.write("\nEXCEPTION: {}\n".format(ex))
            import traceback
            out.write(traceback.format_exc())
            print_out_str("dump_hfi_kms_listeners: exception: {}".format(ex))
        finally:
            try:
                out.close()
            except Exception as ex:
                print_out_str(
                    "dump_hfi_kms_listeners: failed to close output: {}".format(ex))
            else:
                print_out_str(
                    "dump_hfi_kms_listeners: wrote "
                    "display_info/dcp_hfi_kms_listeners.txt")

    def parse(self):
        self.extract_hfi_pal_trace_data()
        self.dump_hfi_dbg()
        self.dump_hfi_kms_listeners()
        self.parse_hfi_queue_packets()
        self.dump_hfi_adapter_pool()
